/** What the emitter needs to know about a window's routes. */
export type EmittedRouting = {
  /** Folder name — the window's id. */
  window: string;
  config: WindowConfig;
  routes: RouteNodes[];
  /** Index in `routes` of the route showing on the first frame. */
  initial: number;
  /**
   * Export name of the window's route signal, or null when it declared none.
   *
   * A window without one is not broken — it renders its initial route and never
   * changes, which is what every screenshot and golden scenario wants.
   */
  routeSignal: string | null;
  /**
   * Export name of the window's Effect layer — `<Window layer={…}>` — or null.
   *
   * Same rule as the route signal: the object survives the compiler/runtime file
   * boundary only as a name, so it must be a module-level export. The host builds
   * a ManagedRuntime from it at launch; absent, no effect machinery ever loads.
   */
  layer: string | null;
  /**
   * Route loaders, indexed by route — how to reference the function to run on
   * navigation, or null where the route has none. Same rule as the layer: a
   * function survives the compiler/runtime boundary only as a name.
   */
  loaders: (LoaderRef | null)[];
  /**
   * The failure overlay's node ids — the synthesized subtree `window-tree.ts`
   * appends to every shell. `root` starts hidden (this feeds `hiddenAtStart`
   * alongside the off-chain routes); `title` and `detail` are the TEXT nodes
   * whose string slots the runtime overwrites, reserved rather than interned
   * because they are dyntext.
   */
  redbox: { root: number; title: number; detail: number } | null;
  /**
   * `<Suspense>` boundaries: each is two sets of node ids and the export names
   * of the resources whose `"pending"` status picks between them. Content
   * starts hidden (a resource is pending at launch by definition), fallback
   * visible — the inverse of every write `applyBoundaries` will make.
   */
  boundaries: { content: number[]; fallback: number[]; names: string[] }[];
  /**
   * `<Show>` boundaries: two sets of node ids and the condition, already
   * resolved to what the artifact contains — an imported name, or an inline
   * `computed(() => …)` expression. `initiallyVisible` is the condition's value
   * at build time; the side losing it ships hidden, so a Show whose cell holds
   * its launch value costs the first frame nothing.
   */
  shows: { content: number[]; fallback: number[]; expr: string; initiallyVisible: boolean }[];
};

/**
 * A route loader, as the artifact references it.
 *
 * A bare page's `export const loader` is a named export, referenced by name. A
 * route object's loader is a property of its default export, which the artifact
 * imports under a synthetic alias and reads the property off.
 */
export type LoaderRef =
  | { kind: "name"; name: string }
  | { kind: "default"; alias: string; specifier: string; prop: string };

/**
 * Nodes hidden on the first frame: everything off the initial route's chain.
 *
 * An ancestor of the active route stays visible, because the active route is
 * rendered *inside* it — that is what makes a layout a layout. Everything else is
 * resident and excluded, which is the measured design: 20 routes with 19 hidden
 * cost 1.39 ms against 6.04 ms before the diff carried changed node indices.
 */
function hiddenAtStart(nodeCount: number, routing: EmittedRouting): number[] {
  const hidden = new Array<number>(nodeCount).fill(0);
  const chain = routeChain(routing.routes, routing.initial);

  for (const [i, route] of routing.routes.entries()) {
    if (chain.has(i)) continue;
    for (const node of route.roots) hidden[node] = 1;
  }

  // The failure overlay. Unlike a route's loading/error trees — which the launch
  // navigation immediately writes over — nothing touches this byte until a failure
  // does, so the emitted column is its only "at rest" state.
  if (routing.redbox) hidden[routing.redbox.root] = 1;

  // Suspense boundaries open on their fallback: every resource is pending at
  // launch by definition, and shipping the column that way means the first frame
  // needs no boundary write at all.
  for (const boundary of routing.boundaries) {
    for (const node of boundary.content) hidden[node] = 1;
  }

  // Shows open on whichever side the condition's build-time value picked.
  for (const show of routing.shows) {
    for (const node of show.initiallyVisible ? show.fallback : show.content) hidden[node] = 1;
  }

  return hidden;
}

export function compile(html: string, css: string): CompileResult {
  return compileTree(parseHtml(html), css);
}

/**
 * Compiles an already-parsed document container. The HTML parser and the JSX
 * runtime both produce this shape, so both authoring front-ends share every
 * downstream stage — cascade, variants, interning, emit.
 */
export function compileTree(
  doc: Element,
  css: string,
  opts: {
    /**
     * Filled in with the node each element became, when a caller needs to find
     * its way back.
     *
     * The router is the caller that does: it splices a page's tree into the
     * window's and then has to know which nodes that page owns, so navigation can
     * hide them. Nothing in the tree carries an identity the IR keeps — node ids
     * are positions — so the mapping has to be handed out while the positions are
     * being assigned or reconstructed by counting afterwards, and counting is the
     * version that breaks the first time a node is dropped.
     */
    nodeOf?: Map<Element, number>;
  } = {},
): CompileResult {
  // UA rules first in the array purely for readability; `Origin.UA` is what
  // actually keeps them below the author's, and it beats specificity.
  const uaSheet = parseCss(UA_SHEET, Origin.UA);
  const authorSheet = parseCss(css);
  const rules = [...uaSheet, ...authorSheet];

  // `@property` registrations from both sheets. Author last, so an app that
  // re-registers one of the UA sheet's properties wins — the same precedence
  // everything else here has.
  const registered = new Map([...uaSheet.properties, ...authorSheet.properties]);

  // `@keyframes` from both sheets, author last for the same reason: two blocks
  // sharing a name means the later one wins, and the author's sheet is later.
  const keyframeBlocks = new Map([...uaSheet.keyframes, ...authorSheet.keyframes]);

  // Assigned as conditions are met during the walk, so bit order is first-use
  // order and a sheet's unused breakpoints cost nothing.
  const media = new MediaBits();

  // `body`, when present, *is* the root container — it receives the window rect,
  // so `body { background: ... }` fills the window as an author expects.
  const elementChildren = doc.children.filter((c): c is Element => c.type === "element");
  const rootEl =
    elementChildren.length === 1 && elementChildren[0]!.tag === "body" ? elementChildren[0]! : doc;

  const styles = new StyleInterner();
  const strings: string[] = [];
  const stringIds = new Map<string, number>();
  const nodes: BuiltNode[] = [];
  const warnings: string[] = [];
  const tweens = new TweenInterner();
  /** Timing diagnostics already reported, so one mistake is one line. */
  const timingWarned = new Set<string>();
  const anim: AnimContext = {
    keyframes: keyframeBlocks,
    styles,
    tweens,
    warn: (message, where) => {
      if (timingWarned.has(message)) return;
      timingWarned.add(message);
      warnings.push(`${where}: ${message}`);
    },
  };
  const textBindings: BuiltTextBinding[] = [];
  const paramBindings: BuiltParamBinding[] = [];
  const dataBindings: BuiltDataBinding[] = [];
  const errorBindings: BuiltErrorBinding[] = [];
  const imageBindings: BuiltImageBinding[] = [];
  const handlers: BuiltHandler[] = [];
  const lists: BuiltList[] = [];
  /** `disabled={signal}`, per element, resolved to control rows after the walk. */
  const disabledCandidates: { node: number; tag: string; ref: unknown; where: string }[] = [];
  /** Everything carrying `autofocus`, in document order. At most one survives. */
  const autofocusCandidates: {
    node: number;
    tag: string;
    focusable: boolean;
    where: string;
  }[] = [];
  /**
   * Where each list splices into its container, recorded while walking and
   * resolved once every container's child array is final.
   *
   * `after` is how many static children the container had when the list was
   * reached, so the anchors are `children[after - 1]` and `children[after]`.
   * It cannot be read at the time: the sibling *following* the list has not
   * been compiled yet.
   */
  const pendingAnchors: Array<{ list: number; container: number; after: number }> = [];
  const editables: BuiltEditable[] = [];
  /**
   * `bind:value={row.title}` sightings, before the list they belong to is known.
   *
   * Collected flat and lifted by [`walkList`], because the walk reaches the element before
   * it finishes the template it is inside. Anything still here at the end was a recorded
   * path outside a `map()` — impossible from JSX, and a build error rather than a silent
   * dead field if it ever becomes possible.
   */
  const itemEditableCandidates: { node: number; path: (string | number)[]; where: string }[] = [];
  // Data-driven classes and checkedness sighted in templates, lifted by their list
  // exactly as editables are.
  const itemFlagCandidates: { node: number; path: (string | number)[]; where: string }[] = [];
  const itemCheckedCandidates: { node: number; path: (string | number)[]; where: string }[] = [];
  /** Node ids of elements carrying `bind:value`, so their text run can be flagged. */
  const editableFields = new Set<number>();

  /**
   * Every named control inside a `<form>`, decided before the walk starts.
   *
   * Before, because the walk *needs* the answer: a named text field with no `bind:value`
   * gets a cell the compiler declares, and its text run has to be bound to that cell as the
   * run is created. Resolving it afterwards would mean revisiting nodes the walk has
   * already finished with.
   *
   * See `fields.ts` — the rules are a browser's, and measured rather than recalled.
   */
  /**
   * Which form owns each control, resolved once and read by three separate questions.
   *
   * Shared with `resolveForms` deliberately: the payload, the default button and the
   * blocking-field count are all counts over *owned* controls, and computing ownership twice
   * is how two of them come to disagree.
   */
  const ownership = formOwnership(rootEl);
  const {
    specs: fieldSpecs,
    cells: fieldCells,
    groups: fieldGroups,
    arrays: fieldArrays,
  } = collectFields(rootEl, (message) => warnings.push(message), ownership);

  /**
   * The element marked `error` in each `field` wrapper, so the walk can bind its run.
   *
   * Read during the walk the same way a declared field cell is, and for the same reason: the
   * run has to be *created* bound, not patched afterwards.
   */
  const messageCellOf = new Map<Element, string>();
  for (const group of fieldGroups) {
    for (const message of group.messages) messageCellOf.set(message.el, message.cell);
  }

  /**
   * The same, for a `<span error />` **inside a row template**.
   *
   * A separate map rather than a second entry in the one above, because the two produce
   * different bindings: a wrapper's message is a cell every reader shares, and a row's is a
   * slot per replica read out of a box indexed by row.
   */
  const rowErrorOf = new Map<Element, { cell: string }>();
  for (const array of fieldArrays) {
    if (array.messageEl !== null && array.rowErrors !== null) {
      rowErrorOf.set(array.messageEl, array.rowErrors);
    }
  }

  /**
   * Every element that got a node, so the label pass can start from markup.
   *
   * A `for=` label points at an element by id, and that element may not have been
   * compiled yet — so this cannot be resolved while walking, and the pass that does
   * it needs the element tree rather than the node arrays. Filled unconditionally,
   * unlike `opts.nodeOf`, which is a caller's optional hook.
   */
  const nodeOfEl = new Map<Element, number>();
  const controls: BuiltControl[] = [];
  /** Image references, ascending by node — the walk is document order. */
  const images: BuiltImage[] = [];
  /** `min`/`max`/`step` for range and number inputs — see `BuiltNumeric`. */
  const numerics: BuiltNumeric[] = [];
  /** Labels in document order, with their node, for the pass below. */
  const labelEls: Array<{ el: Element; node: number }> = [];
  /**
   * Radio group ids, interned per `(form, name)`.
   *
   * Keyed on the form *element* and not just the name, because that is measured:
   * three radios named `plan` were checked at once when two of them sat in their
   * own `<form>` — see BROWSER-FACTS.md, "A radio cannot be unchecked by pointer,
   * and its group is the form". Keying on the name alone would have silently made
   * two independent groups into one, which is the kind of bug that only shows up in
   * a form complicated enough that nobody is watching every radio.
   */
  const groupIds = new Map<string, number>();
  const formIds = new Map<Element, number>();

  /**
   * Per `<option>`, the group its select interned and whether it is the initial pick.
   *
   * Filled by [`walkPicker`] before the options are walked, and read when each one
   * pushes its controls row. A map rather than a lookup off the ancestor path because
   * the path is the wrong shape for it: an option inside an `<optgroup>` is two levels
   * down, and "the select two ancestors up" is a rule that quietly breaks the moment a
   * group is introduced.
   */
  const optionRows = new Map<Element, { group: number; selected: boolean }>();

  /**
   * Marks a `<select>`'s options with their group and their initial selectedness.
   *
   * Called before any of them is walked, so each finds its row waiting when it pushes
   * its controls entry. Shared by the dropdown and the list box because the two differ
   * only in *where* the options end up — the picker box or in flow — and not at all in
   * what a `controls` row for one says.
   *
   * `parts.selected` rather than `parts.chosen`, and that is the whole reason this is a
   * function: a list box may have several selected options and may have none, so "is it
   * the chosen one" cannot be the test any more.
   */
  const markOptions = (select: Element, options: Element[], parts: UaParts): void => {
    const group = optionGroup(select);
    for (const option of options) {
      optionRows.set(option, { group, selected: parts.selected.has(option) });
      labelHosts.set(option, option);
    }
  };

  /**
   * The group id shared by one `<select>`'s options.
   *
   * The same interning table radios use, so the two can never collide — committing an
   * option *is* a radio set, and `Controls::clear_group` is the code that runs. The key
   * is a sentinel rather than a name, because an option's group is its select and a
   * select has no `name` to key on.
   */
  const selectGroups = new Map<Element, number>();
  const optionGroup = (select: Element): number => {
    const existing = selectGroups.get(select);
    if (existing !== undefined) return existing;
    const id = groupIds.size;
    groupIds.set(`\u0000select${selectGroups.size}`, id);
    selectGroups.set(select, id);
    return id;
  };

  /**
   * Per control element, the element whose text run is its label.
   *
   * For a `<select>` that is its `<selectedcontent>`; for an `<option>` it is the
   * option itself. Resolved to node ids after the walk by [`resolveControlLabels`],
   * because the run does not exist yet when the controls row is pushed.
   */
  const labelHosts = new Map<Element, Element>();

  /**
   * The group id for a radio, or -1 when it has no `name`.
   *
   * A nameless radio is in no group: it can be checked and never unchecked, and it
   * clears nothing. That is what a browser does, and -1 says it in a way the engine
   * needs no special case for — "clear every other member of group -1" is naturally
   * empty.
   */
  const radioGroup = (el: Element, path: Element[]): number => {
    const name = el.attrs.get("name");
    if (!name) return -1;

    // The *innermost* enclosing form. `path` is the ancestor chain, so the last one
    // wins, and nested forms — invalid HTML, but parseable — resolve the way the DOM
    // would rather than throwing.
    let form: Element | null = null;
    for (const ancestor of path) if (ancestor.tag === "form") form = ancestor;

    let formId = -1;
    if (form !== null) {
      formId = formIds.get(form) ?? formIds.size;
      formIds.set(form, formId);
    }

    const key = `${formId}\u0000${name}`;
    const existing = groupIds.get(key);
    if (existing !== undefined) return existing;
    const id = groupIds.size;
    groupIds.set(key, id);
    return id;
  };

  /**
   * The one place text can enter the IR, and therefore the one place worth
   * checking that it is text an author actually wrote.
   *
   * A stringified recording proxy is the only way a non-authored string reaches
   * here, and it would otherwise intern cleanly and render as a frozen constant
   * in every row — or, for a route parameter, in every navigation.
   */
  const checkAuthored = (s: string): string => {
    if (isItemSentinel(s)) throw new ItemExpressionError(s);
    if (isParamSentinel(s)) throw new ParamExpressionError(s);
    return s;
  };

  const internString = (s: string): number => {
    checkAuthored(s);
    const existing = stringIds.get(s);
    if (existing !== undefined) return existing;
    const id = strings.length;
    strings.push(s);
    stringIds.set(s, id);
    return id;
  };

  /**
   * Dynamic text gets its own string slot, never shared with an interned literal —
   * the runtime overwrites it, and sharing would corrupt unrelated nodes.
   */
  const reserveSlot = (initial: string): number => {
    checkAuthored(initial);
    const id = strings.length;
    strings.push(initial);
    return id;
  };

  const describe = (path: Element[]) =>
    path
      .map((e) => e.tag + (e.id ? `#${e.id}` : "") + e.classes.map((c) => `.${c}`).join(""))
      .join(" > ");

  /**
   * The matched rules for `el`, with its inline declarations layered on top.
   *
   * Inline beats every selector regardless of specificity, which is what a
   * browser does and what an author expects. It applies to the state cascades
   * too: an inline `color` outranks a `:hover` rule's colour, because that is
   * also what CSS says.
   */
  const withInline = (decls: Map<string, string>, el: Element): Map<string, string> => {
    if (!el.style) return decls;
    for (const [prop, value] of parseInlineStyle(el.style)) {
      // Re-inserted for the same reason as in `collectDecls`: an inline
      // `padding: 0` that merely *replaced* a value would still expand at the
      // cascade's position for `padding`, and a longhand from any matched rule
      // would then apply after it and win — the exact opposite of what inline
      // precedence means.
      decls.delete(prop);
      decls.set(prop, value);
    }
    return decls;
  };

  /**
   * One node's finished style plus its variant run, for the element itself or for
   * one of its pseudo-elements.
   *
   * Extracted so a generated box is not a lesser citizen. `.btn:hover::before`
   * has to work — it is how a UA stylesheet lights up a control's tick on hover —
   * and it only works if the pseudo-element gets its own predicate mask and its
   * own per-combination cascade, exactly as the element does. Sharing the code is
   * what makes that true by construction rather than by a second implementation
   * that drifts.
   *
   * `element === null` is the element itself; anything else is its generated box.
   * Inline `style=` is applied only in the first case: it is an attribute on the
   * element, and a browser does not let it reach `::before`.
   */
  function resolveVariants(
    path: Element[],
    el: Element,
    inherited: ComputedStyle,
    parentVars: VarEnv,
    where: string,
    element: PseudoElement | null,
    /**
     * Declarations to use for properties **no rule set**, applied to every state's
     * cascade.
     *
     * Not a stylesheet, because what needs them is not expressible in one: a
     * `::placeholder` has to be inset by its field's `padding`, and the UA sheet cannot
     * name a value the author chooses. The compiler can, because by here the field's
     * padding is a resolved number.
     *
     * Absent-only, so it is a default and not an override — `input::placeholder { left:
     * 4px }` still wins. And applied inside the per-state loop rather than once, or
     * `input:focus::placeholder` would resolve a cascade without them and jump on focus.
     */
    defaults?: Map<string, string>,
    /**
     * Fields laid over **every** state's resolved style, after the cascade.
     *
     * For `::selection`, whose two colours belong on the originating element's row rather
     * than on a row of their own — a selection is a range inside an existing node, not a
     * box. Over the top rather than as declarations, because there are no property names
     * to declare: `selectionBg` is not `background-color`, and putting the pseudo-element's
     * `background-color` into this element's cascade would paint the *field* blue.
     */
    overlay?: Partial<ComputedStyle>,
    /**
     * This element is the window root, whose box is the viewport.
     *
     * The viewport interprets `overflow: visible` as `auto` — see
     * {@link coerceViewportOverflow} — and the rule has to reach **every** state's
     * resolved style, not just the base: a variant row that kept `VISIBLE` would turn
     * the page unscrollable on hover.
     */
    viewport?: boolean,
  ): {
    style: ComputedStyle;
    styleId: number;
    mask: number;
    run: number[];
    vars: VarEnv;
    decls: Map<string, string>;
  } {
    const inline = (decls: Map<string, string>) => {
      if (defaults !== undefined) {
        for (const [property, value] of defaults) {
          if (!decls.has(property)) decls.set(property, value);
        }
      }
      // Presentational hints (`width`/`height` on an `<img>`) ride this hook too:
      // they lose to every rule the cascade found, because they are filled in only
      // where nothing was declared — which is exactly what HTML says they are.
      if (element === null) return withInline(decls, el);
      return decls;
    };

    /** The cascade's answer with {@link overlay} on top, which is what gets interned. */
    const withOverlay = (resolved: ComputedStyle): ComputedStyle => {
      const laid = overlay === undefined ? resolved : { ...resolved, ...overlay };
      return viewport ? coerceViewportOverflow(laid) : laid;
    };

    const base = inline(collectDecls(rules, path, ["none"], media, 0, element));
    // Custom properties inherit *unless registered otherwise*, so the environment
    // is the parent's with this node's own laid over it and any non-inheriting
    // registration removed — and it is built from the *cascaded* declarations, so
    // `--x` obeys specificity like everything else.
    const vars = extendVarEnv(parentVars, base, registered);
    const style = withOverlay(applyDecls(inherited, base, where, vars, registered, anim));

    // Precomputed variants: the compiler emits finished styles and the runtime
    // only picks an index. Each state is resolved as a full cascade from
    // scratch, not as a patch over the base — see collectDecls.
    const styleId = styles.intern(style);

    // Which predicates this node's styling actually reads. Input state and media
    // conditions share one mask deliberately: they are the same kind of thing to
    // everything downstream, and a node styled by both `:hover` and a breakpoint
    // gets the combination resolved for both rather than one of them.
    let mask = mediaMaskFor(rules, path, media, element);
    for (const [bit, pseudo] of PREDICATE_PSEUDO) {
      if (hasPseudoRule(rules, path, pseudo, element)) mask |= bit;
    }

    /**
     * The one data-driven class this element may carry — `cn({ done: t.done })`
     * with a recorded item path. It compiles exactly like a pseudo-state: the
     * mask gains `Predicate.ROW`, and every combination where the bit is live is
     * cascaded **with the class present**, so `.done` and `.row.done` rules land
     * in their own interned style rows and the engine picks by one bit the list
     * update wrote. One bit, so one such class per element; a second is refused
     * by name rather than mis-sharing the bit.
     *
     * The detection re-runs the pseudo/media scan with the class pushed, because
     * a rule like `.done:hover` is reachable only while the class is on — its
     * hover bit has to join the mask even though no plain rule reads `:hover`.
     */
    const rowNames = [
      ...(el.classWhen
        ? Object.entries(el.classWhen)
            .filter(([, source]) => isRecorder(source))
            .map(([name]) => name)
        : []),
      // The transport form: a variant worker's tree carries plain names where the
      // live tree carried recorders — see `Element.rowClasses`. Both spellings
      // must compile identically, or the toggle variants diverge from the
      // baseline and every toggle looks like it patches the class's fields.
      ...(el.rowClasses ?? []),
    ];
    if (rowNames.length > 1) {
      throw new Error(
        `${where} binds ${rowNames.length} data-driven classes ` +
          `(${rowNames.map((n) => `"${n}"`).join(", ")}); one per element is the limit.\n` +
          `  A data-driven class rides one per-node predicate bit. Style with a single\n` +
          `  class per element, or bind the second class on a child of its own.`,
      );
    }
    const rowClass = rowNames[0] ?? null;
    if (rowClass !== null) {
      mask |= Predicate.ROW;
      el.classes.push(rowClass);
      try {
        mask |= mediaMaskFor(rules, path, media, element);
        for (const [bit, pseudo] of PREDICATE_PSEUDO) {
          if (hasPseudoRule(rules, path, pseudo, element)) mask |= bit;
        }
      } finally {
        el.classes.pop();
      }
    }

    // One entry per *combination*, each resolved as a full cascade with exactly
    // those states active.
    //
    // This is where hover∧focus stops being a precedence question. The old shape
    // resolved three named roles and made the runtime pick one, so a node that
    // was both hovered and focused got whichever role ranked higher and lost the
    // other's declarations entirely. Asking `collectDecls` for `["none", "hover",
    // "focus"]` gets the merge CSS specifies, per property, for free — it always
    // took a *set* of states; nothing ever passed it more than the one.
    //
    // Cost is `2^popcount(mask)` cascades for the handful of interactive nodes,
    // and interning collapses the combinations that resolve identically — which
    // is most of them, since real rules touch disjoint properties.
    const bits = maskBits(mask);
    const run: number[] = new Array(1 << bits.length).fill(styleId);

    for (let combo = 1; combo < 1 << bits.length; combo++) {
      const states: Pseudo[] = ["none"];
      let label = where + (element === null ? "" : `::${element}`);
      // The live set for this combination, as the engine will present it: the
      // actual predicate bits, not the compacted index.
      let live = 0;
      for (let b = 0; b < bits.length; b++) {
        if ((combo & (1 << b)) === 0) continue;
        const bit = bits[b]!;
        live |= bit;
        const pseudo = PREDICATE_PSEUDO.find(([p]) => p === bit)?.[1];
        if (pseudo) {
          states.push(pseudo);
          label += `:${pseudo}`;
        } else if (bit === Predicate.ROW && rowClass !== null) {
          label += `.${rowClass}`;
        } else {
          label += `@${bit}`;
        }
      }

      // Each combination re-derives its own environment: `:hover { --tone: … }`
      // is a legitimate way to theme a state, and reusing the base environment
      // here would resolve the hover cascade against the resting variables.
      // A ROW-live combination cascades with the data-driven class present —
      // that is the entire trick: both answers are compiled, the bit picks.
      const rowOn = rowClass !== null && (live & Predicate.ROW) !== 0;
      if (rowOn) el.classes.push(rowClass!);
      let stateDecls: Map<string, string>;
      try {
        stateDecls = inline(collectDecls(rules, path, states, media, live, element));
      } finally {
        if (rowOn) el.classes.pop();
      }
      const resolvedStyle = applyDecls(
        inherited,
        stateDecls,
        label,
        extendVarEnv(parentVars, stateDecls, registered),
        registered,
        anim,
      );
      run[combo] = styles.intern(withOverlay(resolvedStyle));
    }

    return { style, styleId, mask, run, vars, decls: base };
  }

  /**
   * The generated box for one pseudo-element, or -1 for "not rendered".
   *
   * CSS is explicit that an absent, `normal` or `none` `content` means the
   * pseudo-element **is not rendered at all** — it behaves as `display: none`. So
   * the common case here is returning -1, and that is not a failure: a rule like
   * `.btn::before { color: red }` with no `content` legitimately produces nothing.
   *
   * The box is a real TEXT node. That is the whole substitution for a shadow tree:
   * it lays out in Taffy, paints in the ordinary pass, inherits from its
   * originating element, and carries its own variant run — none of which a
   * paint-time synthesised rect would.
   */
  function walkPseudoElement(
    el: Element,
    path: Element[],
    ownStyle: ComputedStyle,
    parentVars: VarEnv,
    where: string,
    parent: number,
    element: PseudoElement,
  ): number {
    if (!hasPseudoElementRule(rules, path, element)) return -1;

    // Whether the box exists is settled *before* any style is interned.
    //
    // Resolving first and bailing afterwards was the obvious order and it leaked:
    // `.plain::before { color: blue }` with no `content` renders nothing, but its
    // cascade had already put a style in the table that no node points at. One
    // wasted entry per no-content rule, in a `u16`-indexed table — cheap to avoid,
    // and the kind of slow leak that is invisible until the table is full.
    //
    /**
     * The text this box would hold with `states` active, or `null` for no box.
     *
     * Resolved all the way to the final string rather than compared as source,
     * because Tailwind puts a variable in between: `before:content-['x']` emits
     * `--tw-content: 'x'; content: var(--tw-content)`, so *every* rule's `content`
     * is the identical text `var(--tw-content)` and comparing declarations would
     * see agreement where the values differ.
     *
     * The environment is the box's own — `::before { --tick: "✓"; content:
     * var(--tick) }` is legitimate, and resolving against the originating
     * element's vars would miss it.
     */
    const contentFor = (states: Pseudo[]): string | null => {
      const decls = collectDecls(rules, path, states, media, 0, element);
      const raw = decls.get("content");
      if (raw === undefined) return null;

      const substituted = raw.includes("var(")
        ? substituteVars(raw, extendVarEnv(parentVars, decls, registered), 0, registered)
        : raw;
      // CSS drops a declaration whose `var()` cannot resolve, and an absent
      // `content` means no box — so the two arrive at the same answer.
      if (substituted === null) return null;

      try {
        return parseContent(substituted);
      } catch (e) {
        throw new Error(`${where}::${element}: ${(e as Error).message}`);
      }
    };

    const text = contentFor(["none"]);
    if (text === null) return -1;

    // `content` must not vary by state, and this refuses rather than picks.
    //
    // `.box:checked::before { content: "✓" }` is the canonical checkbox tick, and
    // taking the resting value for it — which is what reading only the base
    // cascade does — compiles a tick that never appears. Silent, and it looks
    // like a stylesheet bug rather than a missing feature.
    //
    // It is missing because a node's text is one string slot, while a variant run
    // carries style ids only. Making text vary per predicate is a protocol change
    // (a slot per combination), not a compiler one, so the honest answer today is
    // an error that names the workaround: keep `content` constant and toggle a
    // style property, which is the more common spelling anyway.
    for (const [, pseudo] of PREDICATE_PSEUDO) {
      if (!hasPseudoRule(rules, path, pseudo, element)) continue;
      const stateText = contentFor(["none", pseudo]);
      if (stateText !== text) {
        throw new Error(
          `${where}::${element}: \`content\` cannot depend on \`:${pseudo}\` yet — ` +
            `it resolves to ${JSON.stringify(text)} at rest and ` +
            `${JSON.stringify(stateText ?? "(no box)")} when :${pseudo}.\n` +
            `  A node's text is one string slot and a variant run carries style ids, so ` +
            `per-state text needs a protocol change rather than a compiler one.\n` +
            `  Keep \`content\` the same in both and toggle a style property instead — ` +
            `e.g. \`::before { content: "✓"; color: transparent }\` with ` +
            `\`:${pseudo}::before { color: white }\`.`,
        );
      }
    }

    const inherited = inheritFrom(ownStyle);
    const r = resolveVariants(path, el, inherited, parentVars, where, element);

    const self = nodes.length;
    nodes.push({
      kind: NodeKind.TEXT,
      style: r.styleId,
      mask: r.mask,
      run: r.run,
      text: internString(text),
      parent,
      children: [],
      generated: true,
    });
    return self;
  }

  /**
   * The `::placeholder` box for a field that has a `placeholder` attribute.
   *
   * Beside [`walkPseudoElement`] rather than inside it because the two get their text
   * from opposite places. `::before` exists *because* a rule gave it `content`, and has
   * no box without one; a placeholder's text is in the markup, so the attribute decides
   * whether the box exists and CSS only decides how it looks. Reusing that function
   * would have meant a UA rule inventing `content: attr(placeholder)` and an `attr()`
   * implementation to go with it, to express something already known.
   *
   * The box is `position: absolute` in the UA sheet, so it takes no room and overlays
   * where the text will be — that is what lets paint decide the visibility of a box
   * layout has already placed, with nothing to invalidate when it flips.
   */
  function walkPlaceholder(
    el: Element,
    path: Element[],
    ownStyle: ComputedStyle,
    parentVars: VarEnv,
    where: string,
    parent: number,
  ): number {
    if (!isTextEntryTag(el)) return -1;
    const text = el.attrs.get("placeholder");
    if (text === undefined || text === "") return -1;

    const inherited = inheritFrom(ownStyle);

    // Inset by the field's own padding, because an absolutely positioned box is placed
    // against its containing block's **padding box** while text sits in the *content*
    // box — so `left: 0` is short by exactly `padding-left`, which is what put the
    // placeholder against the border while the typed text was correctly indented.
    //
    // It cannot live in the UA sheet: the sheet would have to name a length the author
    // chooses. Here the field's padding is already a resolved number, so this is a
    // compile-time read of the cascade's own output and costs nothing at run time.
    //
    // Defaults rather than overrides, so `input::placeholder { left: 4px }` still wins.
    const defaults = new Map<string, string>([
      ["left", `${ownStyle.padL}px`],
      ["top", `${ownStyle.padT}px`],
    ]);
    const r = resolveVariants(path, el, inherited, parentVars, where, "placeholder", defaults);

    return (
      nodes.push({
        kind: NodeKind.TEXT,
        style: r.styleId,
        mask: r.mask,
        run: r.run,
        text: internString(text),
        parent,
        children: [],
        // Both: it is a pseudo-element, so its predicates come from the field — which
        // is what makes `input:focus::placeholder` mean what it says — and paint has to
        // know to check emptiness before drawing it.
        generated: true,
        placeholder: true,
      }) - 1
    );
  }

  /**
   * The `::marker` box for an `<li>` — the bullet, or the ordinal.
   *
   * Beside [`walkPlaceholder`] for the same reason that one is beside
   * [`walkPseudoElement`]: the box does not owe its existence to a `content` rule.
   * A browser's marker comes from `display: list-item` plus a *counter*, and both
   * halves of that are compile-time facts here — which li this is among its list's
   * children is knowable the way nothing about a browser's DOM is. So `2.` is a
   * resolved string in the IR and the runtime never counts anything: the
   * compile-time-first answer to CSS counters, for the one place HTML needs them.
   *
   * What this deliberately does not reach:
   *
   * - **An li in a dynamic list gets a bullet even inside `<ol>`**, with a build
   *   warning. Every arena row is stamped from one template, so a per-row ordinal
   *   is a runtime string — exactly the boundary `content` already refuses to
   *   cross for `:checked` ticks.
   * - **Placement is an approximation.** Chrome right-aligns marker text to a
   *   fixed gap from the content edge; with no text-align field the offset here
   *   is estimated from the marker's length at the li's own font size, so `9.`
   *   and `10.` land a couple of pixels apart where Chrome aligns their dots.
   * - `list-style-type` values other than the defaults, `start`, `value`, and
   *   `list-style-position: inside`. All are `li::marker { content: … }` away
   *   for an author, which is also the override that beats every default below.
   */
  function walkMarker(
    el: Element,
    path: Element[],
    ownStyle: ComputedStyle,
    parentVars: VarEnv,
    where: string,
    parent: number,
  ): number {
    if (el.tag !== "li") return -1;
    const list = path.length >= 2 ? path[path.length - 2] : undefined;
    if (list === undefined || !["ul", "ol", "menu"].includes(list.tag)) return -1;

    let text = "•";
    if (list.tag === "ol") {
      const items = list.children.filter((c) => c.type === "element" && c.tag === "li");
      const index = items.indexOf(el);
      if (index !== -1) {
        text = `${index + 1}.`;
      } else {
        // Not among the list's static children: this li is a dynamic-list
        // template, stamped once per row, and an ordinal cannot be one string.
        warnings.push(
          `an <li> inside a dynamic list gets a bullet marker, not its number.\n` +
            `    Every row is stamped from one compiled template, so a per-row ordinal would\n` +
            `    be a runtime string — the same protocol boundary that keeps \`content\` from\n` +
            `    depending on \`:checked\`. Style \`li::marker\` or number the items yourself.\n` +
            `    ${where}`,
        );
      }
    }

    // An author's `li::marker { content: "→" }` replaces the default outright.
    const authored = collectDecls(rules, path, ["none"], media, 0, "marker").get("content");
    if (authored !== undefined) {
      try {
        const parsed = parseContent(authored);
        if (parsed !== null) text = parsed;
      } catch (e) {
        throw new Error(`${where}::marker: ${(e as Error).message}`);
      }
    }

    // Out of flow in the list's 40px gutter, so the marker costs the li no room —
    // the same absolute-box trick ::placeholder uses. The offset estimates the
    // marker's own width at ~0.55em per character plus a 0.4em gap, because there
    // is no text-align field to right-align with; stated in the doc above.
    const offset = (text.length * 0.55 + 0.4) * ownStyle.fontSize;
    const defaults = new Map<string, string>([
      ["position", "absolute"],
      ["left", `${-offset}px`],
      ["top", "0px"],
    ]);

    const inherited = inheritFrom(ownStyle);
    const r = resolveVariants(path, el, inherited, parentVars, where, "marker", defaults);

    return (
      nodes.push({
        kind: NodeKind.TEXT,
        style: r.styleId,
        mask: r.mask,
        run: r.run,
        text: internString(text),
        parent,
        children: [],
        generated: true,
      }) - 1
    );
  }

  /**
   * The `::picker(select)` box for a `<select>`, holding its options.
   *
   * Beside [`walkPlaceholder`] rather than inside [`walkPseudoElement`] for the same
   * reason that one is: `::before` exists *because* a rule gave it `content`, while this
   * box exists because the markup has options to put somewhere. CSS decides only how it
   * looks.
   *
   * # Three things this box is, and why each matters
   *
   * **It is generated**, so its per-node predicates come from its parent — which is what
   * makes the UA sheet's `select:open::picker(select) { display: … }` mean "the picker of
   * an open select" rather than "a picker that is itself open", a state nothing could ever
   * put it in. It is also why the box is never `state.hovered` and never in `interactive`.
   *
   * **It is an overlay**, so it is painted after the tree and hit-tested before it. Both
   * halves are needed and for different reasons: in tree order it would draw *under*
   * whatever follows the select, and `hit_test` prunes a subtree whose parent's box does
   * not contain the point — which a picker hanging below its select never does, making
   * every option unclickable. See `NodeFlags.OVERLAY`.
   *
   * **It is laid out whether or not it is showing**, positioned absolutely by the UA
   * sheet. That is the `::placeholder` trick again and it buys the same thing: opening a
   * picker is a pure paint decision with nothing to invalidate, so it costs no relayout
   * and cannot jank. The cost is laying out the options of every closed select, which is
   * a handful of nodes.
   *
   * # What the options' selectors see
   *
   * `path` is passed through **unchanged** — it still ends at the select, not at this box
   * — so `select > option` matches, and so does `option:first-child`. A browser's picker
   * is a pseudo-element the light-DOM options render into rather than a wrapper they move
   * under, and this is what keeps that true. It is the whole reason the split happens
   * here, at the node level, instead of in `uaParts` where it would have been shorter.
   */
  function walkPicker(
    el: Element,
    path: Element[],
    ownStyle: ComputedStyle,
    parentVars: VarEnv,
    where: string,
    parent: number,
    parts: UaParts,
  ): number {
    if (parts.picker === null) return -1;

    markOptions(el, optionsOf(parts.picker), parts);
    if (parts.selectedContent !== null) labelHosts.set(el, parts.selectedContent);

    const inherited = inheritFrom(ownStyle);
    const r = resolveVariants(path, el, inherited, parentVars, where, "picker");

    const self = nodes.length;
    nodes.push({
      kind: NodeKind.BOX,
      style: r.styleId,
      mask: r.mask,
      run: r.run,
      text: -1,
      parent,
      children: [],
      generated: true,
      overlay: true,
    });

    for (const option of parts.picker) {
      const child = walkChild(option, path, ownStyle, self, r.vars);
      if (child !== -1) nodes[self]!.children.push(child);
    }

    return self;
  }

  /**
   * Whether the sheet mentions `::selection` at all, so the common document pays nothing.
   *
   * The resolution below is one extra cascade per *element*, not per editable — `::selection`
   * inherits, so a rule on `body` has to be seen while walking `body`. Cheap, and skipped
   * entirely when no such rule exists.
   */
  const hasSelectionRules = rules.some((r) =>
    r.selectors.some((s) => s.element === "selection"),
  );

  /**
   * The two `::selection` colours this element *declares*, if any.
   *
   * Only the properties the rule actually set, which is the load-bearing detail. These land
   * on the element's own style row as `selectionBg` / `selectionFg`, and those two **inherit**
   * — so a field with no `::selection` rule of its own must keep what came down from the root,
   * where the UA default is. Writing both unconditionally would overwrite that inherited
   * value with whatever `applyDecls` returned for a cascade that declared nothing, which is
   * the *element's* background and text colour: a field's selection painted in the field's
   * own colours, i.e. invisible.
   *
   * That check is also why resolving against the parent's style rather than the element's own
   * is sound, even though a pseudo-element inherits from its originating element. Only a
   * property the rule declared is ever read, so the base value never survives — and the
   * element's own style does not exist yet at this point, being what this feeds into.
   *
   * Resolved once, in the resting state, and applied to every variant. `input:hover::selection`
   * is therefore not honoured, and that is a deliberate simplification rather than an
   * oversight: a selection only exists while the field is focused, so a state-varying
   * highlight has almost no reachable meaning, and honouring it would mean `2^n` extra
   * cascades on every element in the document.
   */
  function selectionColors(
    path: Element[],
    inherited: ComputedStyle,
    parentVars: VarEnv,
    where: string,
  ): Partial<ComputedStyle> | undefined {
    if (!hasSelectionRules) return undefined;

    const decls = collectDecls(rules, path, ["none"], media, 0, "selection");
    const setsBg = decls.has("background-color") || decls.has("background");
    const setsFg = decls.has("color");
    if (!setsBg && !setsFg) return undefined;

    const vars = extendVarEnv(parentVars, decls, registered);
    const style = applyDecls(inherited, decls, `${where}::selection`, vars, registered, anim);

    return {
      ...(setsBg ? { selectionBg: style.bg } : {}),
      ...(setsFg ? { selectionFg: style.fg } : {}),
    };
  }

  /** Returns the index of the node created for `el`. */
  function walk(
    el: Element,
    path: Element[],
    parentStyle: ComputedStyle,
    parent: number,
    parentVars: VarEnv = EMPTY_VARS,
  ): number {
    const where = describe(path);

    const inherited = inheritFrom(parentStyle);
    const { style, styleId, mask, run, vars } = resolveVariants(
      path,
      el,
      inherited,
      parentVars,
      where,
      null,
      presentationalHints(el),
      { ...selectionColors(path, inherited, parentVars, where), ...colorWellOverlay(el) },
      // The node with no parent is the window root, and its box is the viewport.
      parent === -1,
    );

    const self = nodes.length;
    nodes.push({
      kind: KIND_BY_TAG[el.tag] ?? NodeKind.BOX,
      style: styleId,
      mask,
      run,
      text: -1,
      parent,
      children: [],
      ...(ownsItsPress(el, path) ? { ownsPress: true as const } : {}),
      ...(isTabStop(el, path) ? { tabStop: true as const } : {}),
      // A text-entry element is one line high on its own account, bound or not — a
      // browser does not ask whether anything owns the value before giving the box a
      // height. When it *is* bound the generated run below carries the floor instead,
      // and the flag here is harmless because a node with a child is never measured.
      ...(isTextEntryTag(el) ? { editable: true as const } : {}),
      ...(el.tag === "textarea" ? { textArea: true as const } : {}),
    });
    opts.nodeOf?.set(el, self);
    nodeOfEl.set(el, self);

    // A positive `tabindex` still becomes a tab stop, in document order, and the build
    // says why rather than silently doing something else. Measured: a browser sorts the
    // whole positive group ahead of everything, reached after the document wraps — which
    // makes the order a sort rather than the live-tree walk A3 is built on.
    const explicitTabIndex = tabIndexOf(el);
    if (explicitTabIndex !== null && explicitTabIndex > 0) {
      warnings.push(
        `tabindex="${explicitTabIndex}" on <${el.tag}> is treated as tabindex="0".\n` +
          `    A positive tabindex does not sit where it is written: browsers sort the whole\n` +
          `    positive group ahead of every other stop (measured, probes/tab-order.html), which\n` +
          `    makes tab order a sort rather than a walk of the tree. dziri walks.\n` +
          `    The element is still reachable by Tab, in document order.\n` +
          `    ${where}`,
      );
    }

    // Collected rather than resolved, because a control's *row* index is not final until
    // the walk ends: `replicateListControls` appends replica rows and re-sorts the table.
    if (el.disabledWhen !== undefined) {
      if (!DISABLEABLE.has(el.tag)) {
        warnings.push(
          `disabled={…} on <${el.tag}> does nothing: only a form control can be disabled.\n` +
            `    \`disabled\` is meaningful on input, select, textarea and button — those are the\n` +
            `    elements with a control row for the flag to live on. Anywhere else there is\n` +
            `    nothing to switch off, and no press to swallow.\n` +
            `    ${where}`,
        );
      } else {
        disabledCandidates.push({ node: self, tag: el.tag, ref: el.disabledWhen, where });
      }
    }

    // Collected rather than resolved. Which claim wins depends on which is showing, and
    // that is not known until the engine has a layout — see `resolveAutofocus`.
    if (el.attrs.has("autofocus")) {
      autofocusCandidates.push({
        node: self,
        tag: el.tag,
        // Focusable is wider than tabbable by exactly `tabindex="-1"`, and `autofocus`
        // is the first thing in dziri that needs the wider set: a browser will autofocus
        // an element script can focus, whether or not Tab can reach it.
        focusable: isTabStop(el, path) || tabIndexOf(el) !== null,
        where,
      });
    }

    // A prop given a signal that the attribute map cannot hold. Said once, here, rather
    // than left to be discovered by an author whose `disabled={isBusy}` compiles cleanly
    // and produces a control that is never disabled. See `Element.droppedSignals`.
    for (const prop of el.droppedSignals ?? []) {
      warnings.push(
        `${prop}={…} was given a signal, which is ignored.\n` +
          `    Attributes hold text — a selector compares against text — so a signal here has\n` +
          `    nowhere to go, and <${el.tag}> compiled as though the prop were absent.\n` +
          `    Signals reach an element four ways: bind:value for a field's text,\n` +
          `    cn("x", { on: sig }) for a conditional class, {sig} for a text run, and\n` +
          `    disabled={sig} to switch a control off.\n` +
          `    ${where}`,
      );
    }

    // The data-driven class and checkedness, recorded for the list that owns this
    // template to lift — the same shape as `bind:value={row.title}` below. The
    // compile side already happened in `resolveVariants` (the mask bit and the
    // class-on style rows); these carry the *path* the list update reads.
    if (el.classWhen) {
      for (const [, source] of Object.entries(el.classWhen)) {
        if (!isRecorder(source)) continue;
        itemFlagCandidates.push({ node: self, path: pathOf(source), where });
        break; // one per element; resolveVariants refused a second
      }
    }
    if (el.bindChecked !== undefined && el.bindChecked !== null) {
      if (isRecorder(el.bindChecked)) {
        itemCheckedCandidates.push({ node: self, path: pathOf(el.bindChecked), where });
      }
    }

    if (el.onClick) handlers.push({ node: self, ref: el.onClick, name: "", kind: "click" });
    if (el.onChange) handlers.push({ node: self, ref: el.onChange, name: "", kind: "change" });
    if (el.onFocus) handlers.push({ node: self, ref: el.onFocus, name: "", kind: "focus" });
    if (el.onBlur) handlers.push({ node: self, ref: el.onBlur, name: "", kind: "blur" });
    if (el.onSubmit) handlers.push({ node: self, ref: el.onSubmit, name: "", kind: "submit" });
    if (el.onInvalid) handlers.push({ node: self, ref: el.onInvalid, name: "", kind: "invalid" });

    // A named field with no `bind:value` is editable through the cell the compiler
    // declared for it — the whole reason `<form><input name="email"></form>` works with
    // no state module. `name` is pre-set, so the resolve pass leaves it alone; there is
    // no export to look up, exactly as for a component-local signal.
    const cell = fieldSpecs.get(el)?.cell ?? "";
    if (el.bindValue) {
      // A row's own property rather than a signal — `bind:value={job.title}` inside a
      // `map()`. Collected here and lifted into the list by `walkList`, exactly as a row's
      // handlers are: this node is the *template's*, and the binding belongs to whichever
      // row a replica is rendering.
      if (isRecorder(el.bindValue)) {
        itemEditableCandidates.push({ node: self, path: pathOf(el.bindValue), where });
        editableFields.add(self);
      } else if (isSignal(el.bindValue)) {
        editables.push({ node: self, ref: el.bindValue, name: "" });
        editableFields.add(self);
      } else {
        // A plain string, which the widened prop type now admits. It cannot be a field: a
        // literal has nowhere to store what the user types, and freezing one into the box
        // would look like a working input that forgets every keystroke.
        warnings.push(
          `bind:value on <${el.tag}> was given a plain value, not a signal.\n` +
            `    bind:value is two-way, so it needs somewhere to write: a signal(), or — inside\n` +
            `    a map() row — the row's own property, as in bind:value={job.title}.\n` +
            `    ${where}`,
        );
      }
    } else if (cell !== "" && isTextEntry(el)) {
      editables.push({ node: self, ref: null, name: cell });
      editableFields.add(self);
    } else if (isTextEntry(el)) {
      warnings.push(
        `<${el.tag}${typeOf(el) ? ` type="${typeOf(el)}"` : ""}> has no bind:value, so it cannot ` +
          `be typed into — it compiles to a styled box.\n` +
          `    Add bind:value={someSignal} to make it a field, or give it a name inside a\n` +
          `    <form>, which declares a cell for it and puts it in the payload. A value nobody\n` +
          `    declared has nowhere to live.`,
      );
    }

    if (el.tag === "label") labelEls.push({ el, node: self });

    // An `<img>` is a reference, not content: the row says where the bytes come
    // from, and the host + engine do the rest. `srcset` and sizes-selection are
    // deliberately absent — one URL per image, until a measured need says
    // otherwise. A missing or empty `src` is a broken image by HTML's own rules,
    // and earns no row: there is nothing to fetch.
    if (el.tag === "img") {
      const src = el.attrs.get("src")?.trim();
      // `bind:src={sig}` makes the src dynamic: the binding owns the row's
      // string slot — initialised from the signal's current value — and the
      // worker rewrites it when the signal moves. A static `src` alongside is
      // the fallback for the frame before the first publish... but since the
      // binding applies before the first upload, the signal's value is what
      // the row starts with, and the attribute is ignored. A missing src with
      // no binding is a broken image by HTML's own rules and earns no row.
      if (el.bindSrc && isSignal(el.bindSrc)) {
        const slot = internString(String((el.bindSrc as Signal<string>).value));
        images.push({ node: self, src: slot });
        imageBindings.push({ node: self, slot, ref: el.bindSrc, name: "" });
      } else if (src) {
        images.push({ node: self, src: internString(src) });
      }
    }

    // The numeric envelope a binding needs later — range and number only. The
    // engine positions a thumb in fractions and never reads these; they are for
    // the runtime's half of the value, which is why this is a side table and not
    // three more columns of the shared one.
    const numeric = numericOf(el);
    if (numeric !== null) numerics.push({ ...numeric, node: self });

    const controlKind = controlKindOf(el, path);
    if (needsControlRow(el, path)) {
      // Set by `walkPicker` before this option was walked, so it is here for every
      // option that belongs to a select. An `<option>` written outside one has no row
      // and is in no group, which is what a browser does with it: nothing.
      const option = optionRows.get(el);
      const listbox = listboxOf(el);
      controls.push({
        node: self,
        kind: controlKind,
        group:
          controlKind === ControlKind.RADIO
            ? radioGroup(el, path)
            : (option?.group ?? -1),
        // Only a list box has one, and only the engine can use it: the height is
        // `rows` times an option's row height, and that row height is Skia's ascent +
        // descent + line gap at the resolved font size. Measured as a *ratio* across a
        // 4x font-size range (`probes/select-listbox.html`), which is what rules out
        // compiling a pixel height here — the 17px it looks like at the default font is
        // an instance, not a constant.
        rows: listbox?.rows ?? 0,
        // A range's initial thumb position, computed now because value/min/max/step
        // are all compile-time constants; 65535 ("unset", i.e. mid-track) elsewhere.
        value:
          controlKind === ControlKind.RANGE
            ? rangeInitialPermille(el, numericOf(el)!)
            : 0xffff,
        // Presence, not value: `<input checked>` and `checked=""` both mean checked,
        // which is what `parseAttributes` already normalises to.
        //
        // An option is `CHECKED` when it is selected at rest, which is a rule with two
        // branches and neither is "has the attribute". A dropdown falls back to its first
        // option when none says `selected`; a list box selects nothing at all, and a
        // `multiple` can select several. Deriving it from `uaParts.selected` rather than
        // from the attribute is what keeps the baked label and the engine's initial
        // selection from disagreeing: they are the same decision, made once.
        flags:
          (el.attrs.has("checked") || option?.selected === true ? ControlFlags.CHECKED : 0) |
          (el.attrs.has("disabled") ? ControlFlags.DISABLED : 0) |
          (listbox?.multiple === true ? ControlFlags.MULTIPLE : 0) |
          // `checked={t.done}`: the data owns the tick, so rescan re-reads it —
          // this is the authored, compile-time half; the list update writes the
          // CHECKED bit itself from the row's data.
          (isRecorder(el.bindChecked) ? ControlFlags.DATA_CHECKED : 0),
        // Not knowable yet — the run is a child and children have not been walked.
        label: -1,
        // A file input's dialog config, read on the app thread when the click
        // arrives. Not on the wire: it is compile-time constant and only Bun
        // needs it, so it rides the artifact rather than the shared table.
        accept: controlKind === ControlKind.FILE ? el.attrs.get("accept") : undefined,
        multiple: controlKind === ControlKind.FILE ? el.attrs.has("multiple") : undefined,
      });
    }

    // `::marker` precedes even `::before`, per css-lists; being absolute it does
    // not take a sibling's room either way, but the order costs nothing to state.
    const marker = walkMarker(el, path, style, vars, where, self);
    // `::before` is "an immediate child of the originating element", first in
    // order; `::after` is last. Ordinary children in between — so the generated
    // boxes are siblings of the real content, which is exactly what the spec
    // describes and what makes Taffy lay them out with no special case.
    const before = walkPseudoElement(el, path, style, vars, where, self, "before");
    const after = walkPseudoElement(el, path, style, vars, where, self, "after");
    // Out of flow, so where it sits among its siblings does not matter — unlike the two
    // above, whose whole contract is being first and last.
    const placeholder = walkPlaceholder(el, path, style, vars, where, self);

    // A button whose content is a single static text run keeps the label on the
    // button itself, so paint can centre it without a child node to lay out.
    // A *dynamic* label stays a child node, since the binding addresses a node.
    //
    // A generated box disqualifies the shortcut: the label would be painted by the
    // button while `::before` was a child node, and the two have no way to sit
    // beside each other. Rare enough to be worth the extra node rather than a
    // second layout path.
    // An inline `<svg>` is a replaced element wearing markup: its subtree is
    // serialized back to source and handed to the engine as a data: URL, which
    // the images pipeline already knows how to carry — the loader resolves the
    // bytes (here: out of the URL itself) and the engine's SVG renderer parses
    // them. The children are deliberately NOT walked: a `<path>` is not a CSS
    // box, and letting it become one would draw the graphic and a pile of empty
    // boxes on top of each other.
    if (el.tag === "svg") {
      const src = `data:image/svg+xml,${encodeURIComponent(serializeSvg(el))}`;
      images.push({ node: self, src: internString(src) });
      return self;
    }

    const parts = uaParts(el);
    const kids = parts.children;

    // A list box's options are in `kids` and are walked by the ordinary loop below, so
    // they are marked here — the dropdown's equivalent lives in `walkPicker`, which a
    // list box never reaches. Before the walk, not after: an option pushes its own
    // controls row while being walked and reads this map to fill it.
    if (parts.listbox !== null) markOptions(el, optionsOf(parts.children), parts);
    const onlyText =
      kids.length === 1 && kids[0]!.type === "text" ? (kids[0] as { value: string }).value : null;

    if (nodes[self]!.kind === NodeKind.BUTTON && onlyText !== null && before === -1 && after === -1) {
      nodes[self]!.text = internString(onlyText);
      return self;
    }

    if (marker !== -1) nodes[self]!.children.push(marker);
    if (before !== -1) nodes[self]!.children.push(before);

    // An unbound field gets an empty text run, so *every* text-entry field has one.
    //
    // Written because the placeholder broke the field it was drawn in. The strut lived
    // on the element for unbound fields, justified by "a node with a child is never
    // measured" — and a placeholder is a child, so the moment one existed the field
    // stopped being a leaf, was never measured, and collapsed back to padding height.
    // Visible immediately: the disabled field became a line with its placeholder
    // hanging outside it.
    //
    // Giving it a run instead is the better shape rather than the smaller patch. Both
    // kinds of field are then one thing — a box containing a run that holds the value —
    // so the strut, the placeholder's emptiness test and paint all take one path. It is
    // also where an engine-owned text buffer will write, so nothing here moves again
    // when unbound fields start holding text.
    //
    // A field with a **compiler-declared cell** takes the same run and binds it, which is
    // what makes typing into `<input name="email">` show up: the keystroke splices the
    // cell, the binding rewrites the slot, and the ordinary text path draws it. It also
    // takes this branch when it has children, which only a `<textarea>` can — its content
    // is its *default value*, already read into the cell's initial, so rendering it as a
    // static child as well would draw it twice and never update.
    const ownsRun = isTextEntryTag(el) && el.bindValue === null && cell !== "";
    if (isTextEntryTag(el) && el.bindValue === null && (kids.length === 0 || ownsRun)) {
      const runStyle = styles.intern(textStyle(style));
      const initial = ownsRun ? String(fieldSpecs.get(el)?.initial ?? "") : "";
      const slot = ownsRun ? reserveSlot(initial) : internString("");
      // The field's predicates, projected — `.field:invalid { color }` has to
      // recolour the text the field shows, not just its border.
      const projected = textRunVariants(mask, run);
      const runNode = nodes.push({
        kind: NodeKind.TEXT,
        style: runStyle,
        mask: projected?.mask ?? 0,
        run: projected?.run ?? [runStyle],
        text: slot,
        parent: self,
        children: [],
        editable: true,
      }) - 1;
      nodes[self]!.children.push(runNode);
      if (ownsRun) textBindings.push({ node: runNode, slot, parts: [{ export: cell }] });
    }

    // `<span error />` — its text is its wrapper's message, so the run is created bound to
    // that cell and the authored children are dropped. Dropped rather than kept: whatever is
    // written inside is placeholder prose for the author's benefit, and rendering it as well
    // would show "error goes here" in a shipped app until the first failure.
    // The same element inside a **row** takes a per-row part instead of a cell: one span in a
    // template is `capacity` spans on screen, and a shared cell would put one row's complaint
    // on every one of them. Every replica owns its text slots, so the string is the one part
    // of error display that can differ row by row.
    const messageCell = messageCellOf.get(el);
    const rowError = rowErrorOf.get(el);
    if (messageCell !== undefined || rowError !== undefined) {
      const runStyle = styles.intern(textStyle(style));
      const slot = reserveSlot("");
      const run = nodes.push({
        kind: NodeKind.TEXT,
        style: runStyle,
        mask: 0,
        run: [runStyle],
        text: slot,
        parent: self,
        children: [],
      }) - 1;
      nodes[self]!.children.push(run);
      textBindings.push({
        node: run,
        slot,
        parts: [rowError !== undefined ? { rowError } : { export: messageCell! }],
      });
    }

    for (const child of ownsRun || messageCell !== undefined || rowError !== undefined ? [] : kids) {
      const childIndex = walkChild(child, path, style, self, vars, { mask, run });
      if (childIndex !== -1) nodes[self]!.children.push(childIndex);
    }
    if (after !== -1) nodes[self]!.children.push(after);
    // Last, and it does not matter: absolutely positioned, so it is out of flow and its
    // position among the siblings changes nothing about where anything is drawn.
    if (placeholder !== -1) nodes[self]!.children.push(placeholder);

    // Also last, and for the same reason plus one more: the picker is out of flow *and*
    // out of the paint walk entirely, so where it sits among its siblings decides
    // nothing at all. It has to come after the options' own ancestors are styled, which
    // is why it is here rather than beside `before`.
    const picker = walkPicker(el, path, style, vars, where, self, parts);
    if (picker !== -1) nodes[self]!.children.push(picker);

    return self;
  }

  /**
   * Compiles a list into a LIST node plus an arena of identical item subtrees.
   *
   * The template is compiled once through the ordinary `walk`, so items get the
   * same cascade, inheritance and variants as anything else — the arena is only a
   * layout of node *slots*. Replication then copies those nodes with their links
   * shifted by one stride, which is what keeps item-internal traversal ordinary.
   */
  function walkList(
    node: DynList,
    path: Element[],
    parentStyle: ComputedStyle,
    parent: number,
    parentVars: VarEnv = EMPTY_VARS,
  ): number {
    // Item 0 is compiled normally; its bindings are captured relative to it.
    // Its parent is the *container*, not a wrapper: rows are ordinary children
    // spliced into the container's chain, so a grid container places each row
    // in its own cell and a `justify-content` has more than one item to work
    // with. See `ListTable.container` for what the wrapper cost.
    const arenaStart = nodes.length;
    const bindingsBefore = textBindings.length;
    const templateRoot = walkChild(node.template, path, parentStyle, parent, parentVars);
    const stride = nodes.length - arenaStart;

    if (templateRoot !== arenaStart) {
      throw new Error("list template did not compile to a contiguous subtree");
    }

    // Handlers inside the template belong to the row, not to a fixed node.
    const itemHandlers: BuiltItemHandler[] = [];
    for (let h = handlers.length - 1; h >= 0; h--) {
      const handler = handlers[h]!;
      if (handler.node < arenaStart || handler.node >= arenaStart + stride) continue;
      itemHandlers.unshift({
        offset: handler.node - arenaStart,
        ref: handler.ref,
        name: "",
        kind: handler.kind,
      });
      handlers.splice(h, 1);
    }

    // Two-way bindings inside the template belong to the row too, and for a sharper reason
    // than handlers do: the *target* is per-row, not just the dispatch. Lifted the same way.
    const itemEditables: BuiltItemEditable[] = [];
    for (let e = itemEditableCandidates.length - 1; e >= 0; e--) {
      const candidate = itemEditableCandidates[e]!;
      if (candidate.node < arenaStart || candidate.node >= arenaStart + stride) continue;
      itemEditables.unshift({ offset: candidate.node - arenaStart, path: candidate.path });
      itemEditableCandidates.splice(e, 1);
    }

    // Data-driven classes and checkedness, lifted identically: the offset names the
    // replica node whose control row the list update writes.
    const itemFlags: BuiltItemEditable[] = [];
    for (let e = itemFlagCandidates.length - 1; e >= 0; e--) {
      const candidate = itemFlagCandidates[e]!;
      if (candidate.node < arenaStart || candidate.node >= arenaStart + stride) continue;
      itemFlags.unshift({ offset: candidate.node - arenaStart, path: candidate.path });
      itemFlagCandidates.splice(e, 1);
    }
    const itemChecked: BuiltItemEditable[] = [];
    for (let e = itemCheckedCandidates.length - 1; e >= 0; e--) {
      const candidate = itemCheckedCandidates[e]!;
      if (candidate.node < arenaStart || candidate.node >= arenaStart + stride) continue;
      itemChecked.unshift({ offset: candidate.node - arenaStart, path: candidate.path });
      itemCheckedCandidates.splice(e, 1);
    }

    // Item bindings were recorded as ordinary text bindings; lift them out.
    const raw = textBindings.splice(bindingsBefore);

    // A template that reads nothing from its item is always a mistake.
    //
    // `key` is mandatory precisely because rows have identity, so a keyed list
    // whose rows neither display item data nor handle a per-row event is a row
    // of constants repeated `capacity` times. The usual cause is an expression
    // the recorder cannot see through — the sentinel catches the ones that reach
    // a string, and this catches the rest (a `.filter()`, a destructure, an
    // early return).
    if (raw.length === 0 && itemHandlers.length === 0) {
      throw new Error(
        `list template reads nothing from its item, so every row would render the same\n` +
          `  constants. The callback runs once at build time against a recording proxy: it\n` +
          `  can record a bare property read like \`{t.title}\`, but not a value computed\n` +
          `  from one. If the row genuinely has no dynamic content, use a plain array —\n` +
          `  \`[...items].map(…)\` compiles to literal nodes with no arena.`,
      );
    }
    const slotStart = strings.length;
    const bindings: BuiltItemBinding[] = raw.map((b, i) => ({
      offset: b.node - arenaStart,
      slotOffset: i,
      parts: b.parts,
    }));

    // Re-point item 0's own text slots into its slot block, then reserve blocks
    // for the remaining items so every row has its own mutable strings.
    for (const [i, b] of raw.entries()) {
      nodes[b.node]!.text = reserveSlot(strings[b.slot] ?? "");
      void i;
    }
    for (let item = 1; item < node.capacity; item++) {
      for (let b = 0; b < bindings.length; b++) reserveSlot("");
    }

    // Replicate item 0 into the rest of the arena.
    for (let item = 1; item < node.capacity; item++) {
      const shift = item * stride;
      for (let k = 0; k < stride; k++) {
        const src = nodes[arenaStart + k]!;
        nodes.push({
          kind: src.kind,
          style: src.style,
          mask: src.mask,
          run: [...src.run],
          text: src.text,
          parent: k === 0 ? parent : src.parent + shift,
          children: src.children.map((c) => c + shift),
          ...(src.generated ? { generated: true as const } : {}),
          // Everything that makes a node reachable, and it was all missing.
          //
          // Without these a control in a row worked in the *first* row and was inert in
          // every other: no tab stop, no press target, no control row (see
          // `replicateListControls`). One item hid it completely, because a
          // single-item list only ever uses row 0 — so the bug needed a second item to
          // appear at all, and then looked like a styling problem rather than a
          // structural one.
          ...(src.ownsPress ? { ownsPress: true as const } : {}),
          ...(src.tabStop ? { tabStop: true as const } : {}),
          ...(src.editable ? { editable: true as const } : {}),
          ...(src.textArea ? { textArea: true as const } : {}),
          // The same omission as the four above, one flag further along, and it stayed
          // invisible for the same reason: a replica's `::placeholder` box was `generated`
          // but not a **placeholder**, so the engine never applied the "only while the field
          // is empty" test to it and painted the hint straight over the row's value. Row 0
          // was always right — it is the template — so this needed a second row that had
          // text *and* a placeholder, which is exactly what a repeating form row is.
          ...(src.placeholder ? { placeholder: true as const } : {}),
          // `autofocus` is deliberately **not** replicated. One claim per row is eight
          // claims for a capacity-8 arena, all of them the same element repeated, and
          // "which row gets the caret" is a question the markup has not answered. The
          // template's own claim survives, which is row 0 — the one a reader would mean.
        });
      }
      // Each replica's bound slots live in its own block.
      for (const b of bindings) {
        nodes[arenaStart + shift + b.offset]!.text = slotStart + item * bindings.length + b.slotOffset;
      }
    }

    lists.push({
      container: parent,
      // Resolved after the container's child loop finishes, because the sibling
      // that follows the rows has not been compiled yet. Item 0's subtree is
      // already in `nodes`, so the arena occupies indices the anchors are not
      // allowed to name — which is why these are static children only.
      anchorPrev: -1,
      anchorNext: -1,
      source: node.source,
      exportName: "",
      arenaStart,
      stride,
      capacity: node.capacity,
      keyPath: node.keyPath,
      bindings,
      itemHandlers,
      itemEditables,
      itemFlags,
      itemChecked,
      slotStart,
    });

    // No node of its own. The rows enter the container's chain at run time, so
    // this contributes nothing static and the caller pushes nothing.
    pendingAnchors.push({
      list: lists.length - 1,
      container: parent,
      after: nodes[parent]?.children.length ?? 0,
    });
    return -1;
  }

  /**
   * A text run's variants: its element's, projected onto inherited text fields.
   *
   * A run's style is `textStyle(parent)` — so when a predicate changes the
   * element's `color` or `text-decoration`, the *element's* row swaps and the
   * run's used to stay put: `.done { color }` on a row class, `.field:invalid
   * { color }`, `a:hover { color }` all compiled a variant the text never
   * showed. This projects each of the element's combinations through
   * `textStyle` and keeps only the bits that change the projection — a mask of
   * 0 (a `:focus-visible` ring, a hover background) leaves the run exactly as
   * cheap as before. The engine resolves a TEXT node's predicates against its
   * parent, so the bit that swaps the element's row swaps the run's too.
   */
  function textRunVariants(
    parentMask: number,
    parentRun: readonly number[],
  ): { mask: number; run: number[] } | null {
    if (parentMask === 0) return null;
    const bits = maskBits(parentMask);
    const ids = parentRun.map((id) => styles.intern(textStyle(styles.list[id]!)));

    let mask = 0;
    for (let b = 0; b < bits.length; b++) {
      for (let combo = 0; combo < ids.length; combo++) {
        if (ids[combo] !== ids[combo ^ (1 << b)]) {
          mask |= bits[b]!;
          break;
        }
      }
    }
    if (mask === 0) return null;

    // The child's run over its own (sub)mask. The representative parent
    // combination sets exactly the child's live bits — the bits left out are,
    // by construction, the ones that do not move the projection.
    const childBits = maskBits(mask);
    const run: number[] = new Array(1 << childBits.length);
    for (let c = 0; c < run.length; c++) {
      let parentCombo = 0;
      for (let b = 0; b < childBits.length; b++) {
        if ((c & (1 << b)) !== 0) parentCombo |= 1 << bits.indexOf(childBits[b]!);
      }
      run[c] = ids[parentCombo]!;
    }
    return { mask, run };
  }

  function walkChild(
    node: Node,
    path: Element[],
    parentStyle: ComputedStyle,
    parent: number,
    parentVars: VarEnv = EMPTY_VARS,
    parentRun?: { mask: number; run: number[] },
  ): number {
    if (node.type === "dynlist") return walkList(node, path, parentStyle, parent, parentVars);

    if (node.type === "text" || node.type === "dyntext") {
      const self = nodes.length;

      // Dynamic runs render their literals only until the first `update(state)`.
      const initial =
        node.type === "text"
          ? node.value
          : node.parts.map((p) => ("literal" in p ? p.literal : "")).join("");

      const slot = node.type === "text" ? internString(initial) : reserveSlot(initial);

      const textStyleId = styles.intern(textStyle(parentStyle));
      // The element's predicates, projected — see `textRunVariants`. Null when
      // no predicate moves an inherited text field, which is the common case.
      const projected = parentRun ? textRunVariants(parentRun.mask, parentRun.run) : null;
      nodes.push({
        kind: NodeKind.TEXT,
        style: textStyleId,
        mask: projected?.mask ?? 0,
        run: projected?.run ?? [textStyleId],
        text: slot,
        parent,
        children: [],
        // An empty field is still one line tall. Only a run whose parent is the field
        // gets this, so an ordinary binding that happens to render "" keeps a browser's
        // answer of zero height.
        ...(editableFields.has(parent) ? { editable: true as const } : {}),
      });

      if (node.type === "dyntext") {
        // Route reads, each resolved against a different runtime source, are kept
        // apart rather than pooled into `textBindings`: a parameter is bound by the
        // matcher, data by the loader's success, error by its failure. A run mixing
        // two kinds (or a kind with a signal) is refused, because the emitter has no
        // single place to resolve it.
        const kind = node.parts.some((p) => "param" in p)
          ? "param"
          : node.parts.some((p) => "data" in p)
            ? "data"
            : node.parts.some((p) => "error" in p)
              ? "error"
              : "signal";

        if (kind === "signal") {
          textBindings.push({ node: self, slot, parts: node.parts });
        } else {
          const parts = node.parts.map((p) => {
            if ("literal" in p) return { literal: p.literal };
            if (kind === "param" && "param" in p) return { param: p.param };
            if (kind === "data" && "data" in p) return { data: p.data };
            if (kind === "error" && "error" in p) return { error: p.error };
            throw new Error(
              `a route ${kind} cannot share a text run with a signal or another route read (node ${self}). ` +
                `Render it as its own text run, or derive the value in a computed().`,
            );
          });
          if (kind === "param")
            paramBindings.push({
              node: self,
              slot,
              parts: parts as ({ literal: string } | { param: string })[],
            });
          else if (kind === "data")
            dataBindings.push({
              node: self,
              slot,
              parts: parts as ({ literal: string } | { data: (string | number)[] })[],
            });
          else
            errorBindings.push({
              node: self,
              slot,
              parts: parts as ({ literal: string } | { error: (string | number)[] })[],
            });
        }
      }
      return self;
    }
    return walk(node, [...path, node], parentStyle, parent, parentVars);
  }

  const rootIndex =
    rootEl.type === "element" && rootEl.tag !== "#root"
      ? walk(rootEl, [rootEl], INITIAL_STYLE, -1)
      : walk(rootEl, [], INITIAL_STYLE, -1);

  if (rootEl.tag === "#root" && elementChildren.length > 1) {
    warnings.push(
      `document has ${elementChildren.length} top-level elements; they were wrapped in a synthetic root`,
    );
  }

  // Every container's child array is final now, so the splice points resolve.
  for (const pending of pendingAnchors) {
    const kids = nodes[pending.container]?.children ?? [];
    const list = lists[pending.list]!;
    list.anchorPrev = kids[pending.after - 1] ?? -1;
    list.anchorNext = kids[pending.after] ?? -1;
  }

  resolveActivation(nodes, nodeOfEl, controls, labelEls, warnings);
  resolveControlLabels(nodes, nodeOfEl, controls, labelHosts);
  // A recorded path can only be produced inside a `map()` callback, so every candidate
  // should have been claimed by the list whose template contained it. One left over means
  // an item proxy escaped its callback — reported rather than dropped, because a field
  // bound to nothing looks exactly like a working one until it is typed into.
  for (const orphan of itemEditableCandidates) {
    warnings.push(
      `bind:value={item.${orphan.path.join(".")}} is not inside the map() it belongs to.\n` +
        `    A row's property can only be edited by an element in that row's template, because\n` +
        `    the write goes back into the array through the row a replica is rendering.\n` +
        `    ${orphan.where}`,
    );
  }
  for (const orphan of itemFlagCandidates) {
    warnings.push(
      `cn({ …: item.${orphan.path.join(".")} }) is not inside the map() it belongs to.\n` +
        `    A data-driven class reads a row's property, so it only means something on an\n` +
        `    element in that row's template. Outside one, drive the class with a signal.\n` +
        `    ${orphan.where}`,
    );
  }
  for (const orphan of itemCheckedCandidates) {
    warnings.push(
      `checked={item.${orphan.path.join(".")}} is not inside the map() it belongs to.\n` +
        `    Data-driven checkedness reads a row's property; outside a template, write the\n` +
        `    attribute (\`checked\`) for the authored state instead.\n` +
        `    ${orphan.where}`,
    );
  }

  resolveAutofocus(nodes, autofocusCandidates, warnings);
  // After both resolve passes, because `activates` and a control's `label` are node ids
  // those passes fill in — replicating before them would copy two -1s.
  replicateListControls(nodes, controls, lists);
  replicateListImages(images, lists);
  replicateListNumerics(numerics, lists);
  // After `replicateListControls` for the same reason `resolveDisabled` is: a field's
  // control row is an index into a table that pass appends to and re-sorts.
  const forms = resolveForms(rootEl, nodeOfEl, fieldSpecs, controls, ownership, fieldGroups, fieldArrays, (m) => warnings.push(m));
  // After `replicateListControls`, which appends replica rows and re-sorts: a row index
  // taken before that points at a different control.
  const disabled = resolveDisabled(disabledCandidates, controls, lists);

  return {
    strings,
    styles: styles.list,
    nodes,
    root: rootIndex,
    textBindings,
    paramBindings,
    dataBindings,
    errorBindings,
    imageBindings,
    handlers,
    editables,
    lists,
    media: media.rows().map(({ bit, cond }) => ({
      bit,
      kind:
        cond.axis === "width"
          ? cond.side === "min"
            ? MediaKind.MIN_WIDTH
            : MediaKind.MAX_WIDTH
          : cond.side === "min"
            ? MediaKind.MIN_HEIGHT
            : MediaKind.MAX_HEIGHT,
      value: cond.px,
    })),
    tweens: tweens.tweens,
    keyframes: tweens.keyframes,
    controls,
    images,
    numerics,
    forms,
    fieldCells,
    disabled,
    warnings,
  };
}

/**
 * Fills every node's `activates` — the control a press on it operates.
 *
 * Three steps, and the third is the one worth reading:
 *
 * 1. Each control points at itself.
 * 2. Each `<label>` points at its control: the one named by `for=`, else the first
 *    control in its subtree. Measured, both forms forward — see BROWSER-FACTS.md,
 *    "A label's click is a second, synthetic click on the control".
 * 3. **Every other node inherits from its parent**, in one forward pass. Node ids are
 *    assigned parent-first by `walk`, so a single ascending sweep propagates a
 *    label's target through its whole subtree and a control's through its `::before`
 *    and `::after` boxes — which is what makes clicking a checkbox's *tick* tick it.
 *
 * The sweep stops at anything that owns its own press. A `<button>` inside a label
 * is HTML's "interactive content" exclusion, and without the stop a button in a
 * label would silently toggle the checkbox next to it.
 *
 * A `for=` that names nothing, or names something that is not a control, is a
 * warning rather than an error: it is a typo in markup that renders perfectly, and
 * the label simply stops forwarding. Failing the build over it would be worse than
 * the bug.
 */
function resolveActivation(
  nodes: BuiltNode[],
  nodeOfEl: Map<Element, number>,
  controls: BuiltControl[],
  labels: Array<{ el: Element; node: number }>,
  warnings: string[],
): void {
  if (controls.length === 0) return;

  const controlNodes = new Set(controls.map((c) => c.node));
  for (const control of controls) nodes[control.node]!.activates = control.node;

  const byId = new Map<string, Element>();
  for (const el of nodeOfEl.keys()) {
    const id = el.id;
    if (id !== null && !byId.has(id)) byId.set(id, el);
  }

  /** The first control in `el`'s subtree, in document order. */
  const firstControlIn = (el: Element): number => {
    for (const child of el.children) {
      if (child.type !== "element") continue;
      const node = nodeOfEl.get(child);
      if (node !== undefined && controlNodes.has(node)) return node;
      const deeper = firstControlIn(child);
      if (deeper >= 0) return deeper;
    }
    return -1;
  };

  for (const { el, node } of labels) {
    const target = el.attrs.get("for");
    if (target !== undefined) {
      const named = byId.get(target);
      const namedNode = named === undefined ? undefined : nodeOfEl.get(named);
      if (namedNode === undefined || !controlNodes.has(namedNode)) {
        warnings.push(
          `<label for="${target}"> does not name a form control, so clicking it does nothing`,
        );
        continue;
      }
      nodes[node]!.activates = namedNode;
      continue;
    }

    const wrapped = firstControlIn(el);
    if (wrapped >= 0) nodes[node]!.activates = wrapped;
  }

  for (let i = 0; i < nodes.length; i++) {
    const n = nodes[i]!;
    if (n.activates !== undefined) continue;
    const parent = n.parent;
    if (parent < 0 || parent >= i) continue;
    if (n.ownsPress) continue;
    const inherited = nodes[parent]!.activates;
    if (inherited !== undefined) n.activates = inherited;
  }
}

/**
 * Fills `controls.label` — the text run whose string a control's label lives in.
 *
 * A separate pass for the reason [`resolveActivation`] is one: the answer is a *child*
 * of the node whose row wants it, and a row is pushed before its children are walked.
 *
 * What the engine does with it is swap two slots. Committing an option has to change
 * what the closed control reads, and the engine cannot write the string — Bun owns the
 * tables — so it keeps a per-node slot override and points the select's run at the
 * chosen option's. Two node ids per select is all that takes, and this is where they
 * come from.
 *
 * A control with no run leaves -1: an empty `<option></option>`, or a `<select>` whose
 * button the author wrote without a `<selectedcontent>` in it. Both are legal markup and
 * both mean "nothing to mirror", which the engine reads as "leave the label alone".
 */
function resolveControlLabels(
  nodes: BuiltNode[],
  nodeOfEl: Map<Element, number>,
  controls: BuiltControl[],
  labelHosts: Map<Element, Element>,
): void {
  if (labelHosts.size === 0) return;

  /** The first text run among a node's children, or -1. */
  const runIn = (node: number): number => {
    for (const child of nodes[node]!.children) {
      if (nodes[child]!.kind === NodeKind.TEXT) return child;
    }
    return -1;
  };

  const byNode = new Map<number, number>();
  for (const [control, host] of labelHosts) {
    const controlNode = nodeOfEl.get(control);
    const hostNode = nodeOfEl.get(host);
    if (controlNode === undefined || hostNode === undefined) continue;
    byNode.set(controlNode, runIn(hostNode));
  }

  for (const row of controls) {
    const run = byNode.get(row.node);
    if (run !== undefined) row.label = run;
  }
}


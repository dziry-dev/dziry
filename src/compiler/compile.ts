/**
 * One row of the `numerics` side table: the `min`/`max`/`step` of a range or
 * number input, as floats.
 *
 * A side table beside the IR rather than columns on the shared `controls` table,
 * and that is the boundary doing its job: the engine needs the *fraction* (it
 * positions a thumb with it) but never the mapping — min/max/step are read by
 * the binding when a CHANGE comes back, and by nothing else. NaN where the
 * attribute is absent, which for a number field means "unbounded" and for a
 * range is impossible: its defaults (0, 100, 1) are filled at compile time.
 */
export type BuiltNumeric = {
  node: number;
  min: number;
  max: number;
  step: number;
};

/**
 * The numeric envelope of a range or number input, or null for anything else.
 *
 * Parsed from the attributes with the HTML defaults filled: a range is 0..100
 * by 1, a number unbounded by 1. `value` snapped *into* that envelope is the
 * thumb's initial per-mille for a range; for a number it is only the clamp the
 * binding applies later.
 */
function numericOf(el: Element): BuiltNumeric | null {
  if (el.tag !== "input") return null;
  const type = typeOf(el);
  if (type !== "range" && type !== "number") return null;

  const num = (name: string): number => {
    const raw = el.attrs.get(name)?.trim();
    if (raw === undefined || raw === "") return NaN;
    return Number(raw);
  };
  const or = (v: number, fallback: number) => (Number.isFinite(v) ? v : fallback);

  return type === "range"
    ? { node: -1, min: or(num("min"), 0), max: or(num("max"), 100), step: or(num("step"), 1) }
    : { node: -1, min: num("min"), max: num("max"), step: or(num("step"), 1) };
}

/**
 * A range's initial thumb position, per-mille of the track.
 *
 * `value` clamped into [min, max] and snapped down to a step boundary, which is
 * what a browser does with an out-of-envelope or off-step default. With no
 * `value` at all the answer is the 65535 sentinel — "the author said nothing" —
 * which the engine reads as mid-track.
 */
function rangeInitialPermille(el: Element, numeric: BuiltNumeric): number {
  const raw = el.attrs.get("value")?.trim();
  if (raw === undefined || raw === "") return 0xffff;
  const v = Number(raw);
  if (!Number.isFinite(v)) return 0xffff;

  const { min, max, step } = numeric;
  const span = max - min;
  if (span <= 0) return 0;
  const clamped = Math.min(Math.max(v, min), max);
  const snapped = step > 0 ? min + Math.floor((clamped - min) / step) * step : clamped;
  return Math.round(((snapped - min) / span) * 1000);
}

/**
 * `ControlKind` by tag and `type` attribute.
 *
 * Only the kinds whose activation *does* something are here. The other twenty input
 * types are still real elements with real UA styling; they simply have no press
 * behaviour for the engine to run, so giving them a row would be a row that means
 * "nothing happens".
 *
 * `select` and `option` were absent until the overlay layer existed, on exactly that
 * ground — a `SELECT` that opened nothing would have been a claim the engine could not
 * honour. Both are here now, and the pair is deliberate: a select alone would open a
 * picker whose options could not be chosen.
 *
 * `button` and `a[href]` join them for the keyboard and for nothing else. A pointer
 * press does not need either: a `CLICK` is emitted on whatever was hit, control or not.
 * A *key* press has no "whatever was hit" — it has a focused node — so what Enter and
 * Space mean there has to be looked up, and the measured answers differ per kind in a way
 * nothing else in the tables encodes. See `ControlKind.BUTTON`.
 *
 * **`path` is here for the `<select>`'s own button**, which must not get a kind. That
 * button is the closed control: give it a row and its `activates` points at itself, so a
 * press on the only visible part of a select emits a button click instead of opening the
 * picker. That exact bug has been fixed once already, in `ownsItsPress` — the same
 * exemption for a different reason, which is why both spell it out rather than sharing a
 * helper that would hide two unrelated arguments behind one name.
 */
function controlKindOf(el: Element, path: Element[] = []): number {
  if (el.tag === "select") {
    return listboxOf(el) !== null ? ControlKind.LISTBOX : ControlKind.SELECT;
  }
  if (el.tag === "option") return ControlKind.OPTION;
  if (el.tag === "button") {
    return path[path.length - 2]?.tag === "select" ? ControlKind.NONE : ControlKind.BUTTON;
  }
  // An `<a>` with no destination is not focusable, so no key can reach it and a row
  // would describe a state that cannot happen. Same condition the tab-stop set uses.
  if (el.tag === "a") return el.attrs.has("href") ? ControlKind.LINK : ControlKind.NONE;
  if (el.tag !== "input") return ControlKind.NONE;
  switch ((el.attrs.get("type") ?? "text").toLowerCase()) {
    case "checkbox":
      return ControlKind.CHECKBOX;
    case "radio":
      return ControlKind.RADIO;
    // A slider's press *positions* the thumb — a real behaviour, so a real row.
    // The same press on `date`, `number` or `color` does nothing a table row
    // would describe: the first two are text fields (see TEXT_ENTRY_TYPES) and a
    // color's swatch answers an ordinary CLICK, the picker being a documented
    // deferral. `file` is the one that acts: its press opens the OS dialog.
    case "range":
      return ControlKind.RANGE;
    case "file":
      return ControlKind.FILE;
    default:
      return ControlKind.NONE;
  }
}

/** `type`, lowercased; `""` when absent, which for an `<input>` means `text`. */
function typeOf(el: Element): string {
  return (el.attrs.get("type") ?? "").toLowerCase();
}

/**
 * HTML's *presentational hints*: attributes that style the element at the very
 * bottom of the cascade, losing to every rule and to inline `style=`.
 *
 * Only `<img>`'s `width` and `height` are honoured — the pair a replaced element
 * cannot be sized without while its bytes are still fetching. They arrive as
 * `defaults` in `resolveVariants`, which fills only properties no rule set, so
 * `img { width: 100% }` and `style="width: 40px"` both win, exactly as in a
 * browser.
 *
 * The value grammar is HTML's *dimension* rule: a non-negative integer, read as
 * pixels. `width="50%"` is valid HTML with a percentage meaning, which the style
 * table's plain-pixel `width` cannot express for an image that has not loaded —
 * so it is not a hint here, and the attribute is ignored rather than misread.
 */function presentationalHints(el: Element): Map<string, string> | undefined {
  if (el.tag !== "img") return undefined;
  const hints = new Map<string, string>();
  for (const attr of ["width", "height"] as const) {
    const raw = el.attrs.get(attr);
    if (raw !== undefined && /^\d+$/.test(raw.trim())) {
      hints.set(attr, `${raw.trim()}px`);
    }
  }
  return hints.size > 0 ? hints : undefined;
}

/**
 * The overlay that forces the color well's background to its authored value.
 *
 * Presentational hints lose to the UA sheet (`input { background-color: #ffffff }`),
 * so the swatch color must be applied *after* the cascade via overlay. This is the
 * one case where a content attribute directly becomes a painted pixel with no rule
 * in between — exactly what the overlay slot is for.
 */
function colorWellOverlay(el: Element): Partial<ComputedStyle> | undefined {
  if (el.tag !== "input" || typeOf(el) !== "color") return undefined;
  const raw = el.attrs.get("value")?.trim() ?? "";
  const hex = /^#[0-9a-fA-F]{6}$/.test(raw) ? raw : "#000000";
  // Parse #rrggbb -> 0xFFRRGGBB (ARGB, fully opaque)
  const r = parseInt(hex.slice(1, 3), 16);
  const g = parseInt(hex.slice(3, 5), 16);
  const b = parseInt(hex.slice(5, 7), 16);
  return { bg: (0xff000000 | (r << 16) | (g << 8) | b) >>> 0 };
}

/**
 * An `<svg>` subtree back into source text, for the data: URL the images
 * pipeline carries.
 *
 * The parser (html.ts) keeps attribute *values* verbatim and lowercases the
 * names, so `viewBox` arrives as `viewbox` — the engine's SVG parser accepts
 * both spellings for exactly this reason, and what is lost elsewhere
 * (`linearGradient`) is an element the renderer declines anyway.
 *
 * Escaped as XML: the attribute map holds raw text, and a `d` with a quote in
 * it is a broken document without this. Text children are dropped — SVG text
 * is not in the supported subset, and serializing it would draw nothing while
 * costing the parser an element to skip.
 */
function serializeSvg(el: Element): string {
  const attrs = [...el.attrs]
    .map(([name, value]) => ` ${name}="${value.replaceAll("&", "&amp;").replaceAll('"', "&quot;")}"`)
    .join("");
  const kids = el.children
    .filter((c): c is Element => c.type === "element")
    .map(serializeSvg)
    .join("");
  return `<${el.tag}${attrs}>${kids}</${el.tag}>`;
}

/** The elements `disabled` means something on — the ones a press can reach. */
const DISABLEABLE = new Set(["input", "select", "textarea", "button"]);

/**
 * Whether this element needs a `controls` row at all.
 *
 * A control kind needs one because a press *does* something. A **disabled** form
 * control needs one because a press must do exactly nothing — and that is the fact the
 * engine cannot work out for itself, since `Controls::is_disabled` reads this table and
 * nothing else.
 *
 * The docblock on [`controlKindOf`] argues the other twenty input types earn no row,
 * because a row would say "nothing happens". That is right for an *enabled* field and
 * backwards for a disabled one: "nothing happens" is precisely the claim, and without
 * the row a disabled text field took focus on click and matched no `:disabled` rule.
 * Both were visible in the demo — measured for the first half in BROWSER-FACTS.md, "a
 * disabled control receives no button events at all": no `mousedown`, no `mouseup`, no
 * `click`, and it never took focus.
 *
 * The row's `kind` stays `NONE`, so `Controls::activate` still declines it and no
 * behaviour is invented for a text field. Only the flags are load-bearing.
 *
 * **A text-entry field now earns one whether or not it is disabled**, and `:invalid` is
 * why. Validity is written by Bun into this table and read back as a predicate, so a field
 * with no row has nowhere for the bit to live — and text fields are the ones a schema
 * complains about most. The row costs six integers and says nothing a press can act on.
 *
 * That it is *per node* rather than per element is the point in a list: replicas share a
 * style row, so a conditional class cannot redden one row's input alone, while each replica
 * has its own control row and therefore its own predicate.
 */
function needsControlRow(el: Element, path: Element[] = []): boolean {
  if (controlKindOf(el, path) !== ControlKind.NONE) return true;
  // The *tag* question rather than the typeable one: a readonly field is still a field a
  // schema can reject, and the row is structural rather than a statement about input.
  if (isTextEntryTag(el)) return true;
  // A data-driven class needs somewhere to put its per-node bit, exactly as
  // text-entry inputs got a `NONE`-kind row for `:invalid` in v39. The row is
  // the one per-node place the engine already looks.
  if (el.classWhen && Object.values(el.classWhen).some((s) => isRecorder(s))) return true;
  return DISABLEABLE.has(el.tag) && el.attrs.has("disabled");
}

/**
 * The elements a user would expect to be able to type into.
 *
 * Six `input` keywords plus `textarea`, which is the set a browser routes to one text
 * editor — Blitz does the same, and it is why "one editor" is the whole cost of text
 * entry rather than one per keyword.
 *
 * Used only to warn. A field with no `bind:value` compiles to a correct styled box
 * and then silently ignores every keystroke, which is indistinguishable from a
 * working empty field in a screenshot — the exact failure that let a broken
 * `bind:value` survive this long. `disabled` and `readonly` are excluded because a
 * browser does not accept typing into those either, so there is nothing to warn about.
 */
const TEXT_ENTRY_TYPES = new Set([
  "",
  "text",
  "search",
  "tel",
  "url",
  "email",
  "password",
  /**
   * `number` is typed into as well, and leaving it out was visible.
   *
   * An `<input type="number">` compiled to a box with no editor and no line height: four
   * pixels of border, which is what the forms demo drew where its age field should have been.
   * A browser routes it to the same text editor and adds chrome dziri does not have — a
   * spinner — so being typeable is the part that transfers.
   *
   * `range` *was* here on the same argument and left when it became a real control: a
   * slider's value is its thumb, not text, so there is nothing to type into. Its
   * `min`/`max`/`step` live in the `numerics` table beside the IR, where the binding
   * reads them — see `numericOf`.
   *
   * This set is **not** the implicit-submission blocking set, which is what it used to be as
   * well. That one is measured (`probes/implicit-submission.html`) and was measured over the
   * six above, so widening it here would have silently changed a rule nobody re-measured.
   * See `blocksImplicitSubmission`.
   */
  "number",
  // A date is text the runtime masks, not a widget — the calendar popup is the
  // same deferral `datalist` took, recorded in HTML-ELEMENT-COVERAGE-RESEARCH.md.
  "date",
]);

/**
 * The `input` types the "exactly one field" rule counts, as measured.
 *
 * Deliberately its own set rather than [`TEXT_ENTRY_TYPES`]: the two were one set until
 * `number` had to be typeable, and the blocking membership is a *measurement* over the six
 * text keywords. Whether a `number` blocks implicit submission has not been measured, so it is
 * left out rather than assumed — the probe to settle it is a two-line addition to
 * `probes/implicit-submission.html`.
 */
const BLOCKING_TYPES = new Set(["", "text", "search", "tel", "url", "email", "password"]);

/**
 * A text-entry box, by tag and type alone.
 *
 * Separate from [`isTextEntry`] because the two questions have different answers for a
 * disabled field: it cannot be typed into, so it earns no warning, but it is still one
 * line high — being disabled does not collapse a box in any browser.
 */
function isTextEntryTag(el: Element): boolean {
  if (el.tag === "textarea") return true;
  return el.tag === "input" && TEXT_ENTRY_TYPES.has(typeOf(el));
}

function isTextEntry(el: Element): boolean {
  if (el.attrs.has("disabled") || el.attrs.has("readonly")) return false;
  return isTextEntryTag(el);
}

/**
 * Whether a press on this element is aimed at *it* rather than at a label's
 * control.
 *
 * HTML calls this "interactive content" and excludes it from a label's activation
 * behaviour, which is why a button inside a label does not tick the checkbox beside
 * it. dziri can only produce two kinds of it — a control and a `<button>` — so this
 * is that category narrowed to what is reachable, not a general implementation of
 * it.
 *
 * **A `<select>`'s own button is exempt**, and it has to be. That button is the closed
 * control — it is what the user presses to open the picker — so treating it as
 * independent interactive content stops `activates` propagating into it and the select
 * becomes unclickable. Which is exactly what happened: the button was the node
 * `hit_test` returned, its `activates` was -1, and pressing the only visible part of a
 * `<select>` did nothing at all.
 *
 * The exemption covers the authored spelling as well as the UA-supplied one, because in
 * the spec's model they are the same element — a browser builds it for you unless you
 * write it, and either way it is the select's part rather than a button that happens to
 * be inside one. `path` is what tells them apart from a button nested any deeper, which
 * genuinely is content.
 */
function ownsItsPress(el: Element, path: Element[]): boolean {
  if (el.tag === "button" && path[path.length - 2]?.tag === "select") return false;
  return el.tag === "button" || el.tag === "a" || controlKindOf(el, path) !== ControlKind.NONE;
}

/** Tags that are tab stops on their own account, with no attribute needed. */
const TAB_STOP_TAGS = new Set(["input", "textarea", "select"]);

/**
 * Whether Tab can reach this element — the compile-time half of ROADMAP A3's focus model.
 *
 * Measured, `probes/tab-order.html`, and written against that table rather than against
 * the neighbouring [`ownsItsPress`], which it resembles closely enough to be tempting.
 * The two disagree in three places and every one of them is a real difference:
 *
 * - **`<a>` needs an `href`.** A link with no destination is not focusable at all — not
 *   by Tab, not by script. It is still interactive content for a label's purposes, which
 *   is why the function above does not ask.
 * - **A `<select>`'s own button is not a stop**, so a select is one stop rather than two.
 *   The same exemption `ownsItsPress` makes, for a different reason: there it stops
 *   `activates` being blocked, here it stops the tab order visiting the control twice.
 *   The shared spelling is not a shared cause, so it is written out in both places.
 * - **`<option>` is excluded by being absent from the tag set**, despite having a control
 *   kind and a row. A picker's list is arrowed, never tabbed.
 *
 * `controlKindOf` is deliberately not consulted. A plain `<input type="text">` has no
 * control kind — a press on it does nothing a control table would describe — and it is
 * of course a tab stop. Focusability is a property of the *tag*, and treating it as a
 * property of controlness would silently exclude every text field in the language.
 *
 * Not asked here, because none of it is compile-time: `disabled` (a live predicate bit),
 * `display:none` and `visibility:hidden` (layout facts the engine's walk already skips),
 * and which member of a radio group carries the group's single stop (the checked one).
 *
 * **`tabindex` overrides all of it**, in both directions, which is the whole of its
 * support here — see [`tabIndexOf`]. It needed no new bit and no protocol change, which
 * was worth checking rather than assuming: `NodeFlags.TAB_STOP`'s own comment anticipated
 * a second bit for "focusable but not tabbable", and that second set turns out to be
 * empty in dziri today. A pointer press focuses whatever it hits regardless of any flag,
 * so `tabindex="-1"` is exactly "not a tab stop" and one bit says it.
 */
function isTabStop(el: Element, path: Element[]): boolean {
  const explicit = tabIndexOf(el);
  if (explicit !== null) return explicit >= 0;
  if (el.tag === "a") return el.attrs.has("href");
  if (el.tag === "button") return path[path.length - 2]?.tag !== "select";
  return TAB_STOP_TAGS.has(el.tag);
}

/**
 * The `tabindex` attribute as a number, or null when absent or unparseable.
 *
 * Only the sign is read, and that is deliberate rather than lazy. Measured,
 * `probes/tab-order.html`: a **positive** `tabindex` does not sit where it is written —
 * the whole positive group sorts ahead of everything else, and `div[tabindex="3"]` was
 * reached *after* the document wrapped, as the first stop of the next cycle.
 *
 * dziri refuses that, and the refusal is structural rather than a missing feature.
 * ROADMAP A3's design is that the order **is** a walk of the live tree; honouring a
 * positive `tabindex` would make it a sort with a walk as its tiebreak, which is a
 * different algorithm and one that cannot be a walk at all. The element still becomes a
 * tab stop — dropping it would be an accessibility regression to punish a stylistic
 * choice — it simply takes its place in document order, and the build says so.
 *
 * An unparseable value is `null`, which falls back to the tag rule. HTML says an invalid
 * `tabindex` is ignored, and ignoring it is what falling through does.
 */
function tabIndexOf(el: Element): number | null {
  const raw = el.attrs.get("tabindex");
  if (raw === undefined) return null;
  const n = Number(raw.trim());
  return Number.isInteger(n) ? n : null;
}


/**
 * Marks every element that can hold focus and asked for it, and warns about the rest.
 *
 * **Every** one, not the winner. Choosing is the engine's job, and the reason is a
 * measurement plus a fact about dziri. Measured (`probes/autofocus-hidden.html`): an
 * unfocusable claim neither wins nor aborts — Chromium walks past it to the next. And in
 * dziri a page is fourteen routes with thirteen hidden on the first frame, so several
 * claims are normal and which of them is *showing* is the only thing that decides, which
 * is runtime state. Resolving here would either pick a hidden node or need a compile-time
 * model of routing that would be wrong the first time anything navigated.
 *
 * So the only claims refused here are the ones no runtime state can rescue: an element
 * that cannot hold focus at all. That is silent in a browser and is a genuine mistake —
 * `autofocus` is a global attribute, so it parses happily on a `<div>` and does nothing
 * there forever. The fix is one word, and nobody guesses it from silence.
 *
 * Note what is *not* warned about: two focusable claims. That used to warn "the first
 * claimed it", which was true of the first draft and false of this one — with the walk,
 * a second claim is a fallback rather than a loser.
 */
function resolveAutofocus(
  nodes: BuiltNode[],
  candidates: { node: number; tag: string; focusable: boolean; where: string }[],
  warnings: string[],
): void {
  for (const c of candidates) {
    if (c.focusable) {
      nodes[c.node]!.autofocus = true;
      continue;
    }
    warnings.push(
      `autofocus on <${c.tag}> does nothing: the element cannot hold focus.\n` +
        `    autofocus is a global attribute, so it parses anywhere, but only a focusable\n` +
        `    element is ever focused. Add tabindex="0" to make it one.\n` +
        `    ${c.where}`,
    );
  }
}

/**
 * Every node claiming `autofocus`, ascending. Usually empty, occasionally one per route.
 *
 * Sorted for `findRow`'s binary search in `upload.ts`, which is the same reason the other
 * six sets are sorted — and here sortedness is also the document order the engine's walk
 * needs, though the engine does not rely on that: it re-derives the order from the tree,
 * for exactly the reason `buildTabStops` gives.
 */
/**
 * Whether this element is one of the fields the "exactly one" rule counts.
 *
 * The membership is measured rather than reasoned, and the measurement is worth keeping
 * next to the code because two of the three exclusions are counter-intuitive: a
 * `<select>` does not count, a checkbox does not count, and **a `<textarea>` does not
 * count either** — a form holding one text input and one textarea still submits on Enter.
 */
function blocksImplicitSubmission(el: Element): boolean {
  // `BLOCKING_TYPES`, not the typeable set — see its comment. They were one set until
  // `number` needed a box, and sharing it would have widened a measured rule as a side effect
  // of a layout fix.
  return el.tag === "input" && BLOCKING_TYPES.has(typeOf(el));
}

/**
 * Every `<form>`, with Enter's outcome resolved.
 *
 * A whole browser algorithm collapsing to one integer per form, which is the
 * compile-time-first claim landing about as cleanly as it ever does: which button is
 * first in tree order, whether it is disabled, and how many fields block are all
 * properties of the markup. What is left for run time is one lookup — from the focused
 * node to its form — and one test the host can do from the tags it already has.
 *
 * **Every question here is asked of the form's *owned* controls rather than of its
 * subtree**, and that is measured rather than tidied: a `form="F"` button written outside F
 * is F's default button, a descendant button whose `form=` names another form is *not*, and
 * an associated field outside F still counts towards F's "exactly one blocking field". A
 * subtree scan gets all three wrong. See `fields.ts::formOwnership` for the table.
 */
function resolveForms(
  root: Element,
  nodeOf: Map<Element, number>,
  fieldSpecs: Map<Element, FieldSpec>,
  controls: BuiltControl[],
  ownership: Ownership,
  fieldGroups: FieldGroup[],
  fieldArrays: FieldArray[],
  warn: (message: string) => void,
): BuiltForm[] {
  const out: BuiltForm[] = [];

  /** Whether `path` is `prefix` or sits under it. */
  const startsWith = (path: readonly string[], prefix: readonly string[]): boolean =>
    prefix.every((segment, i) => path[i] === segment);

  /**
   * `validateOn`, checked rather than trusted.
   *
   * Three values, and a fourth spelling is a build warning rather than a silent `submit`:
   * `validateOn="onChange"` is exactly what someone coming from React Hook Form would write,
   * and a form that then only validated on submit would look like a broken feature.
   */
  const validateOnOf = (el: Element): string => {
    // `validate-on`, because a JSX prop is kebab-cased on its way into the attribute map —
    // `kebab("validateOn")`. The undashed spelling is accepted too, since that is what an
    // `.html` document would plausibly write and the parser does not kebab anything.
    //
    // Reading only `validateon` was the first version, and it compiled every form as
    // `"submit"` while the markup said otherwise: no error, no warning, just a feature that
    // did nothing. The generated table is what showed it.
    const raw = el.attrs.get("validate-on") ?? el.attrs.get("validateon");
    if (raw === undefined || raw === "") return "submit";
    if (raw === "submit" || raw === "change" || raw === "blur") return raw;
    warn(
      `validateOn="${raw}" is not one of submit, change or blur — treated as "submit".\n` +
        `    dziri names the trigger rather than the handler, so it is "change" and not\n` +
        `    "onChange". There is no "touched" or "all": a form re-validates as its fields\n` +
        `    change once a submit has failed, whatever this says.`,
    );
    return "submit";
  };

  /**
   * This form's named controls, in document order.
   *
   * From the spec map's insertion order, which *is* document order — `collectFields` walks
   * the whole document once — and that matters beyond tidiness: a field written **before**
   * the form it names comes first in that form's payload, measured. A subtree scan could not
   * produce that order because the field is not in the subtree.
   */
  const fieldsOf = (form: Element): FieldSpec[] =>
    [...fieldSpecs.values()].filter((spec) => spec.form === form);

  const collect = (form: Element): { button: Element | null; blocking: number } => {
    let button: Element | null = null;
    let blocking = 0;
    // Document order, so "the first submit button" means the first in the document among the
    // ones this form owns — which is what the measurement shows and is not the same as the
    // first in the subtree.
    for (const owned of ownership.byForm.get(form) ?? []) {
      if (button === null && isSubmitButton(owned)) button = owned;
      if (blocksImplicitSubmission(owned)) blocking += 1;
    }
    return { button, blocking };
  };

  const visit = (el: Element): void => {
    if (el.tag === "form") {
      const node = nodeOf.get(el);
      if (node !== undefined) {
        const { button, blocking } = collect(el);
        // A **disabled** default button blocks submission outright rather than being
        // skipped in favour of the no-button rule. Measured, and measured specifically:
        // with one field the skip-then-fall-through reading predicts a submit and the
        // block reading predicts nothing, and nothing is what happened.
        const usable = button !== null && !(button as Element).attrs.has("disabled");
        // A spec whose element never became a node cannot be read at run time, so it is
        // dropped rather than emitted pointing at -1. Nothing produces one today —
        // `collectFields` does not descend into a `map()` template, which is the one place
        // an element is compiled somewhere other than where it was written — and it is a
        // cheap guard against a walk that starts skipping something new.
        const specs = fieldsOf(el).filter((spec) => nodeOf.has(spec.el));
        const fields: BuiltField[] = specs.map((spec) => ({
          node: nodeOf.get(spec.el)!,
          kind: spec.kind,
          value: spec.value,
          // `?? ""` covers a submitter, which has no cell and so was given no initial.
          initial: spec.initial ?? "",
          options: spec.options,
          disabled: spec.disabled,
          row: controls.findIndex((row) => row.node === nodeOf.get(spec.el)),
          ref: spec.cell === "" ? spec.el.bindValue : null,
          name: spec.cell,
        }));

        // A wrapper whose element got no node cannot be reached at run time; dropped for the
        // same reason a field would be.
        const groups = fieldGroups
          .filter((g) => g.form === el && nodeOf.has(g.el))
          .map((g) => ({
            node: nodeOf.get(g.el)!,
            path: g.path,
            errorCell: g.errorCell,
            messages: g.messages.map((m) => ({ path: m.path, cell: m.cell })),
            // Which controls are *under* this wrapper, by path prefix. Used for the dirty
            // test, and resolved here because a path comparison is a build-time question.
            fields: specs.flatMap((spec, i) => (startsWith(spec.path, g.path) ? [i] : [])),
          }));

        out.push({
          node,
          button: usable ? nodeOf.get(button as Element) ?? -1 : -1,
          direct: button === null && blocking === 1,
          fields,
          groups,
          arrays: fieldArrays
            .filter((a) => a.form === el)
            .map((a) => ({
              path: a.path,
              source: a.source,
              name: "",
              rowErrors: a.rowErrors?.cell ?? "",
            })),
          validateOn: validateOnOf(el),
          keys: formKeys(specs.map((spec) => ({ path: spec.path, kind: spec.kind, el: spec.el }))),
          // Sorted, because the runtime binary-searches it the way it searches `textAreas`.
          // Every control this form owns, named or not — the *set*, where `fields` is only
          // the part that has a payload entry. Enter pressed in an associated field written
          // outside the form has to find that form, and a parent walk cannot: the field is
          // not a descendant.
          owns: new Int32Array(
            (ownership.byForm.get(el) ?? [])
              .map((owned) => nodeOf.get(owned))
              .filter((n): n is number => n !== undefined)
              .sort((a, b) => a - b),
          ),
          validate: el.validate ?? null,
          validateName: "",
        });
      }
    }
    for (const child of el.children) if (child.type === "element") visit(child);
  };

  visit(root);
  return out;
}

function buildAutofocus(nodes: BuiltNode[]): Int32Array {
  const out: number[] = [];
  for (let i = 0; i < nodes.length; i++) if (nodes[i]!.autofocus) out.push(i);
  return new Int32Array(out);
}

/**
 * Gives every row of a list arena the control rows its template has.
 *
 * A list arena is `capacity` copies of one template subtree, and the copy was structural
 * only — nodes, styles and text slots. Anything held in a *side table* keyed by node id
 * was left behind, and the controls table is the big one: a `<input type=checkbox>` in a
 * row compiled to exactly one control row, for row 0, so the first checkbox toggled and
 * the other seven were painted boxes that swallowed presses.
 *
 * It hid well. A list with one item never uses a row past 0, so every test and every demo
 * with a single-item list behaved perfectly; it needed a second item to appear, and then
 * looked like a paint bug rather than a missing table row.
 *
 * **A radio group is shared across rows**, because `group` is copied unchanged. That is a
 * decision rather than an oversight: rows carrying the same `name` are the markup's way of
 * saying "pick one of these", and one group across the list is what that means. A
 * per-row group would need a per-row `name`, which a template cannot express.
 *
 * `activates` is shifted with the rest, and shifted **only when it points inside the
 * arena** — a label outside the row aiming at a control inside it would otherwise be
 * relocated to a node that has nothing to do with it.
 */
function replicateListControls(
  nodes: BuiltNode[],
  controls: BuiltControl[],
  lists: BuiltList[],
): void {
  let added = false;

  for (const list of lists) {
    const { arenaStart, stride, capacity } = list;
    const end = arenaStart + stride;
    const template = controls.filter((c) => c.node >= arenaStart && c.node < end);

    for (let item = 1; item < capacity; item++) {
      const shift = item * stride;

      for (let k = 0; k < stride; k++) {
        const src = nodes[arenaStart + k]!;
        if (src.activates === undefined) continue;
        const inside = src.activates >= arenaStart && src.activates < end;
        nodes[arenaStart + shift + k]!.activates = inside ? src.activates + shift : src.activates;
      }

      for (const c of template) {
        controls.push({
          node: c.node + shift,
          kind: c.kind,
          group: c.group,
          flags: c.flags,
          label: c.label >= 0 ? c.label + shift : -1,
          rows: c.rows,
          value: c.value,
          accept: c.accept,
          multiple: c.multiple,
        });
        added = true;
      }
    }
  }

  // The engine binary-searches this column, and the rows above were appended after every
  // node the walk had produced — so without this the table is unsorted the moment a list
  // holds a control, and every lookup past the first arena silently misses.
  if (added) controls.sort((a, b) => a.node - b.node);
}

/**
 * The images table's half of arena replication — see `replicateListControls`,
 * which this shadows. An `<img>` inside a `map()` row is one template row and
 * `capacity` rendered copies, and without this every row past the first drew an
 * empty box: same bug shape as the checkbox that only row 0 could toggle.
 *
 * `src` copies unchanged rather than shifting, and that is the difference from
 * `label` above that matters: a string slot is shared, so every replica pointing
 * at the same slot is correct *and* is what makes the engine's per-`src` decode
 * cache fire — one fetch for forty rows of the same avatar.
 */
function replicateListImages(images: BuiltImage[], lists: BuiltList[]): void {
  let added = false;

  for (const list of lists) {
    const { arenaStart, stride, capacity } = list;
    const end = arenaStart + stride;
    const template = images.filter((i) => i.node >= arenaStart && i.node < end);

    for (let item = 1; item < capacity; item++) {
      const shift = item * stride;
      for (const img of template) {
        images.push({ node: img.node + shift, src: img.src });
        added = true;
      }
    }
  }

  // Sorted for the engine's binary search, same as the controls table.
  if (added) images.sort((a, b) => a.node - b.node);
}

/**
 * The numerics table's half of arena replication — same argument as
 * `replicateListImages`: one template row is `capacity` rendered sliders, and a
 * binding reading row 3's `min` must find it. `min`/`max`/`step` copy unchanged;
 * they are constants of the template, not per-row state.
 */
function replicateListNumerics(numerics: BuiltNumeric[], lists: BuiltList[]): void {
  let added = false;

  for (const list of lists) {
    const { arenaStart, stride, capacity } = list;
    const end = arenaStart + stride;
    const template = numerics.filter((n) => n.node >= arenaStart && n.node < end);

    for (let item = 1; item < capacity; item++) {
      const shift = item * stride;
      for (const num of template) {
        numerics.push({ ...num, node: num.node + shift });
        added = true;
      }
    }
  }

  if (added) numerics.sort((a, b) => a.node - b.node);
}

/**
 * Turns each `disabled={signal}` into the set of control rows it writes.
 *
 * Rows rather than a node id, because that is what the runtime needs and resolving it here
 * is free: the controls table is final and sorted by the time this runs.
 *
 * **Plural rows, and the list case is why.** A control inside a list template has one row
 * per replica — `replicateListControls` — so one authored `disabled={sig}` on a row's
 * button has to switch off all `capacity` copies of it. Emitting a single row would
 * disable row 0 and leave the rest live, which is the same shape of bug this session
 * already found in the arena replication, arrived at from the other direction.
 *
 * A candidate with no control row at all is dropped silently, and only one thing produces
 * that: an element in `DISABLEABLE` that got no row because it is a `<select>`'s own
 * UA-supplied `<button>`. The author cannot write that element, so there is nobody to warn.
 */
function resolveDisabled(
  candidates: { node: number; tag: string; ref: unknown; where: string }[],
  controls: BuiltControl[],
  lists: BuiltList[],
): BuiltDisabled[] {
  const out: BuiltDisabled[] = [];

  for (const c of candidates) {
    const nodes: number[] = [c.node];

    // Inside a list template? Then every replica of this offset needs the same flag.
    for (const list of lists) {
      const end = list.arenaStart + list.stride;
      if (c.node < list.arenaStart || c.node >= end) continue;
      for (let item = 1; item < list.capacity; item++) nodes.push(c.node + item * list.stride);
      break;
    }

    const rows: number[] = [];
    for (const node of nodes) {
      const row = controls.findIndex((r) => r.node === node);
      if (row >= 0) rows.push(row);
    }
    if (rows.length > 0) out.push({ rows: new Int32Array(rows), ref: c.ref, name: "" });
  }

  return out;
}

/** Text areas, sorted. The one text field Enter does not submit from. */
function buildTextAreas(nodes: BuiltNode[]): Int32Array {
  const out: number[] = [];
  for (let i = 0; i < nodes.length; i++) if (nodes[i]!.textArea) out.push(i);
  return new Int32Array(out);
}

function buildInteractive(
  nodes: BuiltNode[],
  handlers: BuiltHandler[],
  editables: BuiltEditable[] = [],
  lists: BuiltList[] = [],
  variants?: VariantCompiled,
): number[] {
  const withHandler = new Set(handlers.map((h) => h.node));

  // An editable is interactive because focus is acquired by clicking and
  // `hit_test` only ever returns an `INTERACTIVE` node — so without this a
  // `bind:value` node can never become `state.focused`, the host's `typeInto`
  // never finds a target for the keystroke, and typing does nothing at all.
  //
  // That was the state of the world until this line: both demo editables are a
  // bare `<div bind:value>` with no `hover:` class and no handler, so their masks
  // are 0 and neither qualified under any other clause below. The bug outlived a
  // fix to the layer beneath it — `SDL_StartTextInput` was missing too, and
  // starting it changed nothing, because the events it unblocked arrive addressed
  // to a node that could not hold focus.
  const editable = new Set(editables.map((e) => e.node));

  // Per-row handlers live at an offset inside every replica, so each replica's
  // node has to be interactive — the template's single entry is not enough.
  for (const list of lists) {
    for (const h of list.itemHandlers) {
      for (let item = 0; item < list.capacity; item++) {
        withHandler.add(list.arenaStart + item * list.stride + h.offset);
      }
    }
  }

  const out: number[] = [];
  for (let i = 0; i < nodes.length; i++) {
    const n = nodes[i]!;

    // A generated box is never independently interactive, however many state
    // styles it carries — and it usually carries one, since `:hover::before` is
    // how a control stylesheet is written.
    //
    // Marking it interactive is worse than useless, it is actively wrong.
    // `hit_test` returns the innermost *interactive* node, so the pointer landing
    // on a checkbox's tick would make the tick `state.hovered` and leave the
    // checkbox itself un-hovered — `.check:hover { border-color }` would stop
    // applying exactly when the pointer is over the middle of the control. The
    // box's own state already comes from its parent via `NodeFlags.GENERATED`, so
    // it has nothing to gain and a hover to break.
    if (n.generated) continue;

    // Either source counts: the baseline mask for a node styled by `:hover`
    // directly, the variant mask for one that only gains a state while a toggle
    // is on. The second used to be missed, which emitted a correct hover style
    // onto a node that could never be hovered.
    const stateful = n.mask !== 0 || (variants !== undefined && (variants.masks[i] ?? 0) !== 0);

    // A node that operates a control has to be hittable even with no styling of its
    // own — the `<span>` beside a checkbox is the common case, and `hit_test` only
    // ever returns an `INTERACTIVE` node. Without this the compiler would emit a
    // perfectly correct `activates` that nothing could ever reach, which is the same
    // silent shape as a variant no predicate can select.
    const operates = n.activates !== undefined;

    if (
      n.kind === NodeKind.BUTTON ||
      stateful ||
      operates ||
      editable.has(i) ||
      withHandler.has(i)
    ) {
      out.push(i);
    }
  }
  return out;
}

/**
 * Builds the IR in memory, skipping the emit/import round trip. Used by tests
 * and by dev-mode recompilation; the app itself imports the generated module so
 * the shipping path is the one being validated.
 */
export function toCompiledUi(result: CompileResult): CompiledUi {
  const { firstChild, nextSibling } = flattenLinks(result.nodes);

  const styles = { count: result.styles.length } as Record<string, unknown>;
  for (const [field, ctor] of STYLE_FIELDS) {
    styles[field] = new CTORS[ctor](result.styles.map((s) => s[field]));
  }

  const variants = buildVariants(result.nodes, (i) => {
    const n = result.nodes[i]!;
    return { mask: n.mask, run: n.run };
  });

  return {
    strings: result.strings,
    styles: styles as CompiledUi["styles"],
    media: {
      count: result.media.length,
      bit: new Uint32Array(result.media.map((m) => m.bit)),
      kind: new Uint8Array(result.media.map((m) => m.kind)),
      value: new Float32Array(result.media.map((m) => m.value)),
    },
    nodes: {
      count: result.nodes.length,
      kind: new Uint8Array(result.nodes.map((n) => n.kind)),
      style: new Uint16Array(result.nodes.map((n) => n.style)),
      text: new Int32Array(result.nodes.map((n) => n.text)),
      parent: new Int32Array(result.nodes.map((n) => n.parent)),
      firstChild: new Int32Array(firstChild),
      nextSibling: new Int32Array(nextSibling),
      list: new Int16Array(result.nodes.length).fill(-1),
      hidden: new Uint8Array(result.nodes.length),
      activates: activatesOf(result.nodes),
    },
    variants: {
      count: variants.node.length,
      node: new Int32Array(variants.node),
      mask: new Uint32Array(variants.mask),
      runStart: new Int32Array(variants.runStart),
      slots: new Uint16Array(variants.slots),
    },
    interactive: new Int32Array(
      buildInteractive(result.nodes, result.handlers, result.editables, result.lists),
    ),
    generated: buildGenerated(result.nodes),
    editableBoxes: buildEditableBoxes(result.nodes),
    placeholders: buildPlaceholders(result.nodes),
    overlays: buildOverlays(result.nodes),
    tabStops: buildTabStops(result.nodes),
    autofocus: buildAutofocus(result.nodes),
    textAreas: buildTextAreas(result.nodes),
    // Enter's outcome survives — it is pure structure — while the *fields* do not, for the
    // same reason `handlers` does not: a field holds a cell, and a cell is either an export
    // this path never resolves or one the artifact declares, and there is no artifact here.
    // `compileTree` is where the field table can be inspected, and where its tests look.
    forms: result.forms.map((f) => ({
      node: f.node,
      button: f.button,
      direct: f.direct,
      // Ownership *is* pure structure, so it survives here beside `button` and `direct`.
      owns: f.owns,
      validateOn: f.validateOn as "submit" | "change" | "blur",
      fields: [],
      keys: [],
      // Empty for the reason `fields` is: an array field holds the author's signal, and a
      // signal is a reference this path has no artifact to resolve against.
      arrays: [],
      groups: [],
      validate: null,
    })),
    // Empty on the in-memory path for the same reason `handlers` is: a binding needs its
    // signal resolved to an export, which only the generated-module path does.
    disabledBindings: [],
    // Bindings are resolved and emitted only on the generated-module path; the
    // in-memory IR is used by tests and the variant probe, which are static.
    textBindings: [],
    paramBindings: [],
    dataBindings: [],
    errorBindings: [],
    imageBindings: [],
    handlers: [],
    // The *table* needs no resolution — it is where each arena is and where it
    // splices in, all of it compile-time. Only the binding refs need a signal,
    // so returning an empty table here made every list invisible to anything
    // using the in-memory IR, and a test that walked one would have read
    // `undefined` and quietly agreed with itself.
    lists: listTable(result.lists),
    tweens: tweenTable(result.tweens),
    keyframes: keyframeTable(result.keyframes),
    controls: controlTable(result.controls),
    images: imageTable(result.images),
    numerics: numericTable(result.numerics),
    root: result.root,
  };
}

